//! Emits Rust (`ujuc protocol rust`) against the `uju::net::wire` runtime: a module
//! file per namespace, so `namespace game.core;` lands in `game/core/mod.rs`
//! under a root `mod.rs`. A namespace's file changes only with what it
//! declares, or with what it uses from others; message ids, the fingerprint,
//! and the dispatch enums, which change with any message, live in the root.
//!
//! Each struct and message `Foo` becomes the owned `Foo`, which
//! encodes into a caller's buffer, and `FooView`, which validates an encoding
//! once and then reads it in place. Every layout comes from [`Wire`], so the
//! code agrees with every other backend byte for byte. Consts become
//! `SCREAMING_SNAKE_CASE` constants beside the types of their scope.

use std::cell::RefCell;
use std::collections::BTreeMap;
use std::path::PathBuf;

use crate::backend::{self, Backend, Error, GeneratedFile};
use crate::case;
use crate::ir::wire::{Int, Layout, Sequence, Size, Slot, Width, Wire};
use crate::ir::{
    ConstId, ConstValue, Constraints, DefKind, Direction, Field, NamespaceId, Number, Schema, Type,
    TypeId, TypeKind,
};

/// Where generated code finds the runtime, aliased as `__w` in each module.
const RUNTIME: &str = "::uju::net::wire";
/// The file each module is emitted into, in a directory named after it; the
/// root module's is at the top.
const FILE: &str = "mod.rs";
/// The first line of every file, holding [`MARKER`].
///
/// [`MARKER`]: crate::backend::MARKER
const HEADER: &str = "// @generated by `ujuc protocol rust`. Do not edit.";
/// Lints generated modules are exempt from.
const ALLOW: &str = "#[allow(non_camel_case_types, non_snake_case, missing_docs, clippy::all)]";

const RESULT: &str = "::core::result::Result";
const OPTION: &str = "::core::option::Option";
const STRING: &str = "::std::string::String";
const VEC: &str = "::std::vec::Vec";

/// View methods a field accessor must not shadow; such fields get a
/// trailing `_`.
const VIEW_METHODS: &[&str] = &[
    "decode",
    "decode_unchecked",
    "validate",
    "to_owned",
    "as_bytes",
];

pub struct Rust {
    /// The peer to generate, as in [`Options::direction`]. Types only one
    /// side needs get only that side: a server decodes `in` messages and
    /// encodes `out` ones.
    ///
    /// [`Options::direction`]: crate::backend::Options::direction
    pub direction: Option<Direction>,
}

impl Backend for Rust {
    fn generate(&self, schema: &Schema) -> Result<Vec<GeneratedFile>, Error> {
        let wire = backend::wire(schema)?;
        let direction = self
            .direction
            .filter(|direction| *direction != Direction::Bi);
        let generator = Generator::new(schema, &wire, direction)?;
        Ok(generator.files())
    }
}

/// Handler branches for the messages one peer receives (`ujuc dispatch
/// rust`).
pub struct RustDispatch {
    /// `In` for a server, `Out` for a client.
    pub direction: Direction,
}

impl Backend for RustDispatch {
    fn generate(&self, _schema: &Schema) -> Result<Vec<GeneratedFile>, Error> {
        Err(Error::new("dispatch generation is not implemented yet"))
    }
}

/// The traits an owned type can derive beyond `Debug`, `Clone`, and
/// `PartialEq`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct Traits {
    eq: bool,
    hash: bool,
    default: bool,
    copy: bool,
}

const ALL: Traits = Traits {
    eq: true,
    hash: true,
    default: true,
    copy: true,
};

struct Generator<'a> {
    schema: &'a Schema,
    wire: &'a Wire,
    /// `In` or `Out`; `None` for both peers.
    direction: Option<Direction>,
    /// The Rust name of each declaration, indexed by [`TypeId`]: its path
    /// joined, as `MyResponseResult` for an enum nested in `MyResponse`.
    names: Vec<String>,
    /// The module each declaration lives in, as Rust identifiers.
    modules: Vec<Vec<String>>,
    /// The Rust name of each const, indexed by [`ConstId`], and the module
    /// it lives in.
    const_names: Vec<String>,
    const_modules: Vec<Vec<String>>,
    traits: Vec<Traits>,
    /// Whether each declaration is encoded, or decoded, by this peer.
    encode: Vec<bool>,
    decode: Vec<bool>,
    /// Whether a fixed-size struct's bytes need checks beyond their size,
    /// filled in on demand.
    checked: RefCell<Vec<Option<bool>>>,
}

impl<'a> Generator<'a> {
    fn new(
        schema: &'a Schema,
        wire: &'a Wire,
        direction: Option<Direction>,
    ) -> Result<Generator<'a>, Error> {
        unsupported(schema)?;
        let len = schema.defs.len();
        let names = schema.defs.iter().map(|def| ident(&def.name)).collect();
        let modules = (0..len)
            .map(|index| module(schema, TypeId(index)))
            .collect();
        let const_names = const_names(schema)?;
        let const_modules = schema
            .consts
            .iter()
            .map(|item| scope_module(schema, item.namespace, item.parent))
            .collect();
        let (encode, decode) = roles(schema, direction);
        let generator = Generator {
            schema,
            wire,
            direction,
            names,
            modules,
            const_names,
            const_modules,
            traits: traits(schema),
            encode,
            decode,
            checked: RefCell::new(vec![None; len]),
        };
        generator.check_names()?;
        Ok(generator)
    }

    /// Rejects declarations whose Rust names collide within a module, as
    /// `a.B` beside `a.BView`, or the module of `a.Foo`'s nested types beside
    /// a namespace `a.foo`.
    fn check_names(&self) -> Result<(), Error> {
        let mut seen: BTreeMap<(Vec<String>, String), String> = BTreeMap::new();
        let mut errors = Vec::new();
        // Consts are values, so they never meet a type, but `MaxHp` and
        // `MAXHp` are both `MAX_HP`.
        let mut values: BTreeMap<(&[String], &str), ConstId> = BTreeMap::new();
        for (index, name) in self.const_names.iter().enumerate() {
            let key = (&self.const_modules[index][..], name.as_str());
            if let Some(previous) = values.insert(key, ConstId(index)) {
                errors.push(format!(
                    "`{}` and `{}` both generate `{name}`",
                    self.schema.const_qualified(previous),
                    self.schema.const_qualified(ConstId(index))
                ));
            }
        }
        let mut claim = |module: &[String], name: String, owner: String| {
            let key = (module.to_vec(), name);
            match seen.get(&key) {
                Some(previous) if *previous != owner => errors.push(format!(
                    "`{previous}` and `{owner}` both generate `{}`",
                    key.1
                )),
                Some(_) => {}
                None => {
                    seen.insert(key, owner);
                }
            }
        };
        for namespace in &self.schema.namespaces {
            let segments: Vec<String> = namespace.name.iter().map(|name| ident(name)).collect();
            for depth in 1..=segments.len() {
                let owner = format!("namespace {}", namespace.name[..depth].join("."));
                claim(&segments[..depth - 1], segments[depth - 1].clone(), owner);
            }
        }
        for (index, def) in self.schema.defs.iter().enumerate() {
            let owner = self.schema.qualified(TypeId(index));
            let module = &self.modules[index];
            if let Some(parent) = def.parent {
                let (name, outer) = module.split_last().expect("nested in a module");
                let owner = format!("declarations nested in {}", self.schema.qualified(parent));
                claim(outer, name.clone(), owner);
            }
            claim(module, self.names[index].clone(), owner.clone());
            if !matches!(def.kind, DefKind::Enum(_)) {
                claim(module, format!("{}View", self.names[index]), owner);
            }
        }
        for (index, item) in self.schema.consts.iter().enumerate() {
            if let Some(parent) = item.parent {
                let module = &self.const_modules[index];
                let (name, outer) = module.split_last().expect("nested in a module");
                let owner = format!("declarations nested in {}", self.schema.qualified(parent));
                claim(outer, name.clone(), owner);
            }
        }
        for (name, generated) in [
            ("FINGERPRINT", true),
            ("InboundMessage", self.dispatches(Direction::In)),
            ("OutboundMessage", self.dispatches(Direction::Out)),
        ] {
            if generated {
                claim(&[], name.to_string(), format!("the generated `{name}`"));
            }
        }
        // A variant qualified by its namespace can still meet another
        // message's: `aB.c.M` and `a.bC.M` are both `ABCM`.
        for (way, messages, name) in [
            (Direction::In, self.wire.inbound(), "InboundMessage"),
            (Direction::Out, self.wire.outbound(), "OutboundMessage"),
        ] {
            if !self.dispatches(way) {
                continue;
            }
            let mut seen = BTreeMap::new();
            for (variant, id) in self.variants(messages).into_iter().zip(messages) {
                if let Some(previous) = seen.insert(variant.clone(), *id) {
                    errors.push(format!(
                        "`{}` and `{}` both generate `{name}::{variant}`",
                        self.schema.qualified(previous),
                        self.schema.qualified(*id)
                    ));
                }
            }
        }
        if !errors.is_empty() {
            return Err(Error::new(errors.join("\n")));
        }
        Ok(())
    }

    /// Whether the dispatch enum of messages travelling `way` is generated:
    /// the peer receiving them decodes them.
    fn dispatches(&self, way: Direction) -> bool {
        let messages = match way {
            Direction::In => self.wire.inbound(),
            _ => self.wire.outbound(),
        };
        !messages.is_empty() && self.direction.is_none_or(|direction| direction == way)
    }

    fn files(&self) -> Vec<GeneratedFile> {
        let mut root = Module::default();
        let mut defs: Vec<TypeId> = (0..self.schema.defs.len()).map(TypeId).collect();
        defs.sort_by_cached_key(|id| self.schema.qualified(*id));
        for namespace in &self.schema.namespaces {
            let mut module = &mut root;
            for segment in &namespace.name {
                module = module.children.entry(ident(segment)).or_default();
                module.file = true;
            }
        }
        for id in defs {
            let mut module = &mut root;
            for segment in &self.modules[id.0] {
                module = module.children.entry(segment.clone()).or_default();
            }
            module.defs.push(id);
        }
        let mut consts: Vec<ConstId> = (0..self.schema.consts.len()).map(ConstId).collect();
        consts.sort_by_cached_key(|id| self.schema.const_qualified(*id));
        for id in consts {
            let mut module = &mut root;
            for segment in &self.const_modules[id.0] {
                module = module.children.entry(segment.clone()).or_default();
            }
            module.consts.push(id);
        }
        let mut files = Vec::new();
        self.file(&root, &mut Vec::new(), &mut files);
        files
    }

    /// Emits `module`, the root or a namespace, as its own file, and each
    /// namespace below it as theirs.
    fn file(&self, module: &Module, path: &mut Vec<String>, files: &mut Vec<GeneratedFile>) {
        let root = path.is_empty();
        let mut out = Out::default();
        out.line(HEADER);
        let namespaces: Vec<&String> = module
            .children
            .iter()
            .filter(|(_, child)| child.file)
            .map(|(name, _)| name)
            .collect();
        if !namespaces.is_empty() {
            out.line("");
            for name in namespaces {
                out.line(ALLOW);
                out.line(format!("pub mod {name};"));
            }
        }
        if root {
            out.line("");
            out.line("/// A hash of the schema; peers with different fingerprints cannot talk.");
            out.line(format!(
                "pub const FINGERPRINT: u64 = 0x{:016x};",
                self.wire.fingerprint()
            ));
        }
        self.module(&mut out, module, path);
        if root {
            self.ids(&mut out);
            for way in [Direction::In, Direction::Out] {
                if self.dispatches(way) {
                    self.dispatch(&mut out, way);
                }
            }
        }
        // A raw identifier names its file without the `r#`.
        let mut file: PathBuf = path.iter().map(|s| s.trim_start_matches("r#")).collect();
        file.push(FILE);
        files.push(GeneratedFile::new(file, out.finish()));

        for (name, child) in &module.children {
            if child.file {
                path.push(name.clone());
                self.file(child, path, files);
                path.pop();
            }
        }
    }

    /// Writes `module`'s declarations, and the modules of their nested
    /// types inline; namespaces get files of their own.
    fn module(&self, out: &mut Out, module: &Module, path: &mut Vec<String>) {
        if !module.defs.is_empty() {
            out.line("");
            out.line(format!("use {RUNTIME} as __w;"));
        }
        if !module.consts.is_empty() {
            out.line("");
        }
        for id in &module.consts {
            self.constant(out, *id);
        }
        for id in &module.defs {
            out.line("");
            match &self.schema.def(*id).kind {
                DefKind::Enum(item) => self.enumeration(out, *id, item),
                DefKind::Struct(item) => self.object(out, *id, &item.fields, path),
                DefKind::Message(item) => {
                    self.object(out, *id, &item.fields, path);
                    self.message(out, *id);
                }
            }
        }
        for (name, child) in &module.children {
            if child.file {
                continue;
            }
            out.line("");
            out.line(ALLOW);
            out.line(format!("pub mod {name} {{"));
            path.push(name.clone());
            self.module(out, child, path);
            path.pop();
            out.line("}");
        }
    }

    // -----------------------------------------------------------------------
    // Declarations

    fn constant(&self, out: &mut Out, id: ConstId) {
        let item = self.schema.constant(id);
        let (ty, value) = match (&item.ty, &item.value) {
            (_, ConstValue::Int(value)) => (self.schema.kind_name(&item.ty), value.to_string()),
            (TypeKind::F32, ConstValue::Float(value)) => {
                ("f32".into(), format!("{:?}", *value as f32))
            }
            (_, ConstValue::Float(value)) => ("f64".into(), format!("{value:?}")),
            (_, ConstValue::Bool(value)) => ("bool".into(), value.to_string()),
            (_, ConstValue::String(value)) => ("&str".into(), string_literal(value)),
        };
        out.line(format!(
            "pub const {}: {ty} = {value};",
            self.const_names[id.0]
        ));
    }

    fn enumeration(&self, out: &mut Out, id: TypeId, item: &crate::ir::Enum) {
        let name = &self.names[id.0];
        let repr = item.repr.name();
        out.line(format!("#[repr({repr})]"));
        out.line("#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Default)]");
        out.line(format!("pub enum {name} {{"));
        for (index, variant) in item.variants.iter().enumerate() {
            if index == 0 {
                out.line("#[default]");
            }
            out.line(format!("{} = {},", ident(&variant.name), variant.value));
        }
        out.line("}");
        out.line("");
        out.line(format!("unsafe impl __w::Enum for {name} {{"));
        out.line(format!("type Bytes = [u8; {}];", item.repr.size()));
        out.line("");
        out.line(format!(
            "fn from_bytes(bytes: Self::Bytes) -> {OPTION}<Self> {{"
        ));
        out.line(format!("match {repr}::from_le_bytes(bytes) {{"));
        for variant in &item.variants {
            out.line(format!(
                "{} => Some({name}::{}),",
                variant.value,
                ident(&variant.name)
            ));
        }
        out.line("_ => None,");
        out.line("}");
        out.line("}");
        out.line("");
        out.line("fn to_bytes(self) -> Self::Bytes {");
        out.line(format!("(self as {repr}).to_le_bytes()"));
        out.line("}");
        out.line("}");
    }

    fn object(&self, out: &mut Out, id: TypeId, fields: &[Field], module: &[String]) {
        let layout = self.wire.layout(id);
        let name = &self.names[id.0];
        let traits = self.traits[id.0];
        let mut derives = vec!["Debug", "Clone"];
        if traits.copy {
            derives.push("Copy");
        }
        derives.push("PartialEq");
        if traits.eq {
            derives.push("Eq");
        }
        if traits.hash {
            derives.push("Hash");
        }
        if traits.default {
            derives.push("Default");
        }
        out.line(format!("#[derive({})]", derives.join(", ")));
        if fields.is_empty() {
            out.line(format!("pub struct {name} {{}}"));
        } else {
            out.line(format!("pub struct {name} {{"));
            for field in fields {
                out.line(format!(
                    "pub {}: {},",
                    ident(&field.name),
                    self.field_owned(field, module)
                ));
            }
            out.line("}");
        }

        let object = Object {
            name: self.schema.path(id).join("."),
            layout,
            fields,
            module,
        };
        out.line("");
        out.line(format!("impl {name} {{"));
        if self.encode[id.0] {
            let max = match layout.size.max() {
                Some(max) => format!("Some({max})"),
                None => "None".to_string(),
            };
            out.line(format!(
                "pub const MAX_ENCODED_SIZE: {OPTION}<usize> = {max};"
            ));
            out.line("");
            out.line("pub fn encoded_size(&self) -> usize {");
            self.encoded_size(out, &object);
            out.line("}");
            out.line("");
            out.line("/// Writes the encoding to the start of `buf`, which must hold at least");
            out.line("/// [`Self::encoded_size`] bytes, and returns its length.");
            out.line(format!(
                "pub fn encode(&self, buf: &mut [u8]) -> {RESULT}<usize, __w::EncodeError> {{"
            ));
            out.line(format!("__w::en::encode(self, buf, {:?})", object.name));
            out.line("}");
        }
        if self.decode[id.0] {
            if self.encode[id.0] {
                out.line("");
            }
            out.line("/// Validates `buf` as one encoding and copies it out.");
            out.line(format!(
                "pub fn decode(buf: &[u8]) -> {RESULT}<{name}, __w::DecodeError> {{"
            ));
            out.line(format!(
                "{name}View::decode(buf).map(|view| view.to_owned())"
            ));
            out.line("}");
        }
        out.line("}");

        if self.encode[id.0] {
            out.line("");
            self.encoder(out, &object, name);
        }
        if self.decode[id.0] {
            out.line("");
            self.view(out, &object, name);
        }
    }

    fn message(&self, out: &mut Out, id: TypeId) {
        let name = &self.names[id.0];
        out.line("");
        out.line(format!("impl __w::Message for {name} {{"));
        out.line(format!(
            "const NAME: &'static str = {:?};",
            self.schema.qualified(id)
        ));
        out.line("}");
    }

    /// Every message's ids, in the root: one message added or removed
    /// renumbers those after it, whatever their namespace.
    fn ids(&self, out: &mut Out) {
        for (way, messages, name) in [
            (Direction::In, self.wire.inbound(), "Inbound"),
            (Direction::Out, self.wire.outbound(), "Outbound"),
        ] {
            let constant = name.to_uppercase();
            for id in messages {
                let ty = self.path(*id, &[], &self.names[id.0]);
                out.line("");
                out.line(format!("impl {RUNTIME}::{name} for {ty} {{"));
                out.line(format!(
                    "const {constant}_ID: u16 = {};",
                    self.message_id(*id, way)
                ));
                out.line("}");
            }
        }
    }

    /// The id of message `id` among those travelling `way`.
    fn message_id(&self, id: TypeId, way: Direction) -> u16 {
        let ids = self.wire.ids(id);
        match way {
            Direction::In => ids.inbound,
            _ => ids.outbound,
        }
        .expect("a message travelling `way`")
    }

    /// The enum of every message travelling `way`, decoded by id.
    fn dispatch(&self, out: &mut Out, way: Direction) {
        let (name, messages, receiver) = match way {
            Direction::In => ("InboundMessage", self.wire.inbound(), "server receives"),
            _ => ("OutboundMessage", self.wire.outbound(), "client receives"),
        };
        let variants = self.variants(messages);
        out.line("");
        out.line(format!(
            "/// A message a {receiver}, decoded by its id and viewed in place."
        ));
        out.line("#[derive(Debug, Clone, Copy)]");
        out.line(format!("pub enum {name}<'a> {{"));
        for (variant, id) in variants.iter().zip(messages) {
            out.line(format!("{variant}({}),", self.root_view(*id)));
        }
        out.line("}");
        out.line("");
        out.line(format!("impl<'a> {name}<'a> {{"));
        out.line(format!(
            "pub fn decode(id: u16, buf: &'a [u8]) -> {RESULT}<Self, {RUNTIME}::DecodeError> {{"
        ));
        out.line("match id {");
        for (variant, id) in variants.iter().zip(messages) {
            let view = self.path(*id, &[], &format!("{}View", self.names[id.0]));
            out.line(format!(
                "{} => {view}::decode(buf).map(Self::{variant}),",
                self.message_id(*id, way)
            ));
        }
        out.line(format!("_ => Err({RUNTIME}::DecodeError::unknown(id)),"));
        out.line("}");
        out.line("}");
        out.line("");
        out.line("pub fn id(&self) -> u16 {");
        out.line("match self {");
        for (variant, id) in variants.iter().zip(messages) {
            out.line(format!(
                "Self::{variant}(_) => {},",
                self.message_id(*id, way)
            ));
        }
        out.line("}");
        out.line("}");
        out.line("}");
    }

    /// Dispatch variant names: each message's Rust name, or its qualified
    /// name in Pascal case where two namespaces share a name.
    fn variants(&self, messages: &[TypeId]) -> Vec<String> {
        messages
            .iter()
            .map(|id| {
                let name = &self.names[id.0];
                let shared = messages
                    .iter()
                    .filter(|other| self.names[other.0] == *name)
                    .count()
                    > 1;
                if !shared {
                    return name.clone();
                }
                let namespace = self.schema.namespace(self.schema.def(*id).namespace);
                let mut variant: String = namespace.name.iter().map(|s| case::pascal(s)).collect();
                variant.push_str(name);
                variant
            })
            .collect()
    }

    /// A message's view type from the root module.
    fn root_view(&self, id: TypeId) -> String {
        let view = self.path(id, &[], &format!("{}View", self.names[id.0]));
        if self.is_fixed_def(id) {
            format!("&'a {view}")
        } else {
            format!("{view}<'a>")
        }
    }

    // -----------------------------------------------------------------------
    // Encoding

    fn encoded_size(&self, out: &mut Out, object: &Object) {
        let layout = object.layout;
        if let Size::Fixed(size) = layout.size {
            out.line(format!("{size}"));
            return;
        }
        out.line(format!("let mut size = {};", layout.head));
        for (field, slot) in object.fields.iter().zip(&layout.fields) {
            let access = format!("self.{}", ident(&field.name));
            match slot {
                Slot::Optional { .. } => {
                    let size = self.fixed_size(&field.ty);
                    out.line(format!("if {access}.is_some() {{"));
                    out.line(format!("size += {size};"));
                    out.line("}");
                }
                Slot::Var { presence, .. } => {
                    let size = self.size(&field.ty);
                    // Counted items take only their count's bytes.
                    if presence.is_none() && !size.contains('v') {
                        out.line(format!("size += {size};"));
                        continue;
                    }
                    if presence.is_some() {
                        out.line(format!("if let Some(v) = &{access} {{"));
                    } else {
                        out.line("{");
                        out.line(format!("let v = &{access};"));
                    }
                    out.line(format!("size += {size};"));
                    out.line("}");
                }
                Slot::Bit(_) | Slot::OptionalBit { .. } | Slot::At(_) => {}
            }
        }
        out.line("size");
    }

    fn encoder(&self, out: &mut Out, object: &Object, name: &str) {
        let layout = object.layout;
        let vars = layout.vars as usize;
        let width = layout.boundary.bytes() as usize;
        out.line(format!("impl __w::Encode for {name} {{"));
        out.line(format!(
            "const MAX_ENCODED_SIZE: {OPTION}<usize> = {name}::MAX_ENCODED_SIZE;"
        ));
        out.line("");
        out.line("fn encoded_size(&self) -> usize {");
        out.line(format!("{name}::encoded_size(self)"));
        out.line("}");
        out.line("");
        out.line(format!(
            "fn encode(&self, buf: &mut [u8]) -> {RESULT}<usize, __w::EncodeError> {{"
        ));
        out.line(format!("{name}::encode(self, buf)"));
        out.line("}");
        out.line("");
        // An object without fields writes nothing.
        let writer = if object.fields.is_empty() { "_w" } else { "w" };
        out.line(format!(
            "fn write(&self, {writer}: &mut __w::en::Writer<'_>) -> {RESULT}<(), __w::EncodeError> {{"
        ));
        if vars > 1 {
            out.line("let start = w.pos();");
        }

        if layout.bitmap > 0 {
            out.line(format!("let mut bits = [0u8; {}];", layout.bitmap));
            for (field, slot) in object.fields.iter().zip(&layout.fields) {
                let access = format!("self.{}", ident(&field.name));
                match *slot {
                    Slot::Bit(bit) => {
                        out.line(format!("if {access} {{"));
                        out.line(set_bit(bit));
                        out.line("}");
                    }
                    Slot::OptionalBit { presence, value } => {
                        out.line(format!("if let Some(v) = {access} {{"));
                        out.line(set_bit(presence));
                        out.line("if v {");
                        out.line(set_bit(value));
                        out.line("}");
                        out.line("}");
                    }
                    Slot::Optional { presence }
                    | Slot::Var {
                        presence: Some(presence),
                        ..
                    } => {
                        out.line(format!("if {access}.is_some() {{"));
                        out.line(set_bit(presence));
                        out.line("}");
                    }
                    Slot::At(_) | Slot::Var { presence: None, .. } => {}
                }
            }
            out.line("w.put(&bits)?;");
        }

        for (field, slot) in object.fields.iter().zip(&layout.fields) {
            if let Slot::At(_) = slot {
                let label = object.field(field);
                out.line("{");
                out.line(format!("let v = &self.{};", ident(&field.name)));
                self.write(out, &field.ty, "v", &label);
                out.line("}");
            }
        }
        if vars > 1 {
            out.line(format!("let bounds = w.zeros({})?;", (vars - 1) * width));
        }
        for (field, slot) in object.fields.iter().zip(&layout.fields) {
            if let Slot::Optional { .. } = slot {
                let label = object.field(field);
                out.line(format!("if let Some(v) = &self.{} {{", ident(&field.name)));
                self.write(out, &field.ty, "v", &label);
                out.line("}");
            }
        }
        for (field, slot) in object.fields.iter().zip(&layout.fields) {
            let Slot::Var { slot, presence } = *slot else {
                continue;
            };
            let label = object.field(field);
            let access = format!("self.{}", ident(&field.name));
            if presence.is_some() {
                out.line(format!("if let Some(v) = &{access} {{"));
            } else {
                out.line("{");
                out.line(format!("let v = &{access};"));
            }
            self.write(out, &field.ty, "v", &label);
            out.line("}");
            let slot = slot as usize;
            if slot + 1 < vars {
                let at = if slot == 0 {
                    "bounds".to_string()
                } else {
                    format!("bounds + {}", slot * width)
                };
                out.line(format!("w.end({at}, start, {width})?;"));
            }
        }
        out.line("Ok(())");
        out.line("}");
        out.line("}");
    }

    /// Writes `v`, a `&T` for the owned type of `ty`, through `w`.
    fn write(&self, out: &mut Out, ty: &Type, v: &str, raw: &str) {
        let label = format!("{raw:?}");
        if let Some(int) = IntInfo::of(ty) {
            match int.repr {
                Int::Native(_) => {
                    if int.constrained() {
                        out.line(format!(
                            "__w::en::range(*{v}, {}, {}, {label})?;",
                            int.lit(int.lo),
                            int.lit(int.hi)
                        ));
                    }
                    out.line(format!("w.put(&{v}.to_le_bytes())?;"));
                }
                Int::Biased { width, .. } => {
                    out.line(format!(
                        "__w::en::range(*{v}, {}, {}, {label})?;",
                        int.lit(int.lo),
                        int.lit(int.hi)
                    ));
                    out.line(format!(
                        "w.put(&((*{v}).wrapping_sub({}) as {}).to_le_bytes())?;",
                        int.lit(int.lo),
                        unsigned(width)
                    ));
                }
            }
            return;
        }
        match &ty.kind {
            TypeKind::F32 | TypeKind::F64 => {
                if let Some(args) = float_args(ty) {
                    out.line(format!("__w::en::float(*{v}, {args}, {label})?;"));
                }
                out.line(format!("w.put(&{v}.to_le_bytes())?;"));
            }
            TypeKind::Bool => out.line(format!("w.put(&[*{v} as u8])?;")),
            TypeKind::Entity => {
                out.line(format!("w.put(&{v}.to_bits().to_le_bytes())?;"));
            }
            TypeKind::String => {
                if let Some(args) = length_args(&ty.constraints) {
                    out.line(format!("__w::en::length({v}.len(), {args}, {label})?;"));
                }
                out.line(format!("w.put({v}.as_bytes())?;"));
            }
            TypeKind::Bytes => {
                // A fixed length is the array's own.
                if ty.constraints.fixed_length().is_none()
                    && let Some(args) = length_args(&ty.constraints)
                {
                    out.line(format!("__w::en::length({v}.len(), {args}, {label})?;"));
                }
                out.line(format!("w.put({v})?;"));
            }
            TypeKind::Array(item, _) => {
                if is_raw_byte(item) {
                    out.line(format!("w.put({v})?;"));
                } else {
                    out.line(format!("for v in {v}.iter() {{"));
                    self.write(out, item, "v", raw);
                    out.line("}");
                }
            }
            TypeKind::Vec(item) | TypeKind::Set(item) => {
                if let Some(args) = length_args(&ty.constraints) {
                    out.line(format!("__w::en::length({v}.len(), {args}, {label})?;"));
                }
                match self.wire.sequence(ty).expect("a sequence") {
                    Sequence::Packed { .. }
                        if matches!(ty.kind, TypeKind::Vec(_)) && is_raw_byte(item) =>
                    {
                        out.line(format!("w.put({v})?;"));
                    }
                    Sequence::Packed { .. } => {
                        out.line(format!("for v in {v}.iter() {{"));
                        self.write(out, item, "v", raw);
                        out.line("}");
                    }
                    Sequence::Counted { count } => {
                        out.line(format!("w.len({}, {v}.len())?;", count.bytes()));
                    }
                    Sequence::Prefixed { count, prefix } => {
                        out.line(format!(
                            "__w::en::prefixed(w, {v}.iter(), {}, {}, |w, v| {{",
                            count.bytes(),
                            prefix.bytes()
                        ));
                        self.write(out, item, "v", raw);
                        out.line("Ok(())");
                        out.line("})?;");
                    }
                }
            }
            TypeKind::Map(key, value) => {
                if let Some(args) = length_args(&ty.constraints) {
                    out.line(format!("__w::en::length({v}.len(), {args}, {label})?;"));
                }
                match self.wire.sequence(ty).expect("a sequence") {
                    Sequence::Packed { .. } => {
                        out.line(format!("for (k, v) in {v}.iter() {{"));
                        self.write(out, key, "k", raw);
                        self.write(out, value, "v", raw);
                        out.line("}");
                    }
                    Sequence::Counted { count } => {
                        out.line(format!("w.len({}, {v}.len())?;", count.bytes()));
                    }
                    Sequence::Prefixed { count, prefix } => {
                        out.line(format!(
                            "__w::en::prefixed(w, {v}.iter(), {}, {}, |w, (k, v)| {{",
                            count.bytes(),
                            prefix.bytes()
                        ));
                        self.write(out, key, "k", raw);
                        self.write(out, value, "v", raw);
                        out.line("Ok(())");
                        out.line("})?;");
                    }
                }
            }
            TypeKind::Named(id) => match self.schema.def(*id).kind {
                DefKind::Enum(_) => {
                    out.line(format!("w.put(__w::Enum::to_bytes(*{v}).as_ref())?;"));
                }
                _ => out.line(format!("__w::Encode::write({v}, w)?;")),
            },
            _ => unreachable!("integers are handled above"),
        }
    }

    /// The encoded size of `v`, a `&T` for the owned type of `ty`.
    fn size(&self, ty: &Type) -> String {
        if let Size::Fixed(size) = self.wire.size(ty) {
            return size.to_string();
        }
        match &ty.kind {
            TypeKind::String | TypeKind::Bytes => "v.len()".to_string(),
            TypeKind::Vec(item) | TypeKind::Set(item) => {
                match self.wire.sequence(ty).expect("a sequence") {
                    Sequence::Packed { item: 1 } => "v.len()".to_string(),
                    Sequence::Packed { item } => format!("v.len() * {item}"),
                    Sequence::Counted { count } => count.bytes().to_string(),
                    Sequence::Prefixed { count, prefix } => format!(
                        "__w::en::prefixed_size(v.iter(), {}, {}, |v| {})",
                        count.bytes(),
                        prefix.bytes(),
                        self.size(item)
                    ),
                }
            }
            TypeKind::Map(key, value) => match self.wire.sequence(ty).expect("a sequence") {
                Sequence::Packed { item: 1 } => "v.len()".to_string(),
                Sequence::Packed { item } => format!("v.len() * {item}"),
                Sequence::Counted { count } => count.bytes().to_string(),
                Sequence::Prefixed { count, prefix } => {
                    let key = self.fixed_size(key);
                    let value = self.size(value);
                    let entry = if key == 0 {
                        value
                    } else {
                        format!("{key} + {value}")
                    };
                    format!(
                        "__w::en::prefixed_size(v.iter(), {}, {}, |(_, v)| {entry})",
                        count.bytes(),
                        prefix.bytes()
                    )
                }
            },
            TypeKind::Named(_) => "__w::Encode::encoded_size(v)".to_string(),
            _ => unreachable!("only strings, bytes, collections, and structs vary in size"),
        }
    }

    // -----------------------------------------------------------------------
    // Views

    fn view(&self, out: &mut Out, object: &Object, name: &str) {
        let layout = object.layout;
        let fixed = layout.size.fixed();
        let view = format!("{name}View");
        let (lt, bytes) = if fixed.is_some() {
            ("'_", "&self.0")
        } else {
            ("'a", "self.buf")
        };
        let (ty, generics) = match fixed {
            Some(_) => (view.clone(), String::new()),
            None => (format!("{view}<'a>"), "<'a>".to_string()),
        };

        match fixed {
            Some(size) => {
                out.line(format!(
                    "/// [`{name}`], read in place; borrowed as `&{view}`."
                ));
                out.line("#[repr(transparent)]");
                out.line("#[derive(Clone, Copy)]");
                out.line(format!("pub struct {view}([u8; {size}]);"));
            }
            None => {
                out.line(format!("/// [`{name}`], read in place."));
                out.line("#[derive(Clone, Copy)]");
                out.line(format!("pub struct {view}<'a> {{"));
                out.line("buf: &'a [u8],");
                out.line("}");
            }
        }

        out.line("");
        out.line(format!("impl{generics} {ty} {{"));
        let (input, output) = match fixed {
            Some(_) => ("&[u8]", format!("&{view}")),
            None => ("&'a [u8]", "Self".to_string()),
        };
        out.line("/// Validates `buf` as exactly one encoding.");
        out.line(format!(
            "pub fn decode(buf: {input}) -> {RESULT}<{output}, __w::DecodeError> {{"
        ));
        out.line("Self::validate(buf)?;");
        out.line("// SAFETY: just validated.");
        out.line("Ok(unsafe { Self::decode_unchecked(buf) })");
        out.line("}");
        out.line("");
        out.line("/// # Safety");
        out.line("///");
        out.line("/// `buf` must hold exactly one encoding [`Self::validate`] accepts.");
        out.line(format!(
            "pub unsafe fn decode_unchecked(buf: {input}) -> {output} {{"
        ));
        match fixed {
            Some(_) => out.line(format!("unsafe {{ __w::cast::<{view}>(buf) }}")),
            None => out.line(format!("{view} {{ buf }}")),
        }
        out.line("}");
        out.line("");
        out.line(format!(
            "pub fn validate(buf: &[u8]) -> {RESULT}<(), __w::DecodeError> {{"
        ));
        out.line(format!("__w::de::size(buf, {:?})?;", object.name));
        out.line(format!(
            "<{} as __w::Validate>::validate_at(buf, 0)",
            if fixed.is_some() {
                view.clone()
            } else {
                format!("{view}<'_>")
            }
        ));
        out.line("}");
        out.line("");
        let as_bytes = if fixed.is_some() { "&[u8]" } else { "&'a [u8]" };
        out.line(format!("pub fn as_bytes(&self) -> {as_bytes} {{"));
        out.line(bytes);
        out.line("}");
        out.line("");
        out.line(format!("pub fn to_owned(&self) -> {name} {{"));
        if object.fields.is_empty() {
            out.line(format!("{name} {{}}"));
        } else {
            out.line(format!("{name} {{"));
            for field in object.fields {
                let read = format!("self.{}()", accessor(&field.name));
                let owned = if field.optional {
                    optional(&read, &self.owned_from(&field.ty, "v"))
                } else {
                    self.owned_from(&field.ty, &read)
                };
                out.line(format!("{}: {owned},", ident(&field.name)));
            }
            out.line("}");
        }
        out.line("}");

        let optionals = self.optionals(object);
        let start = match optionals.as_str() {
            "" => layout.head.to_string(),
            list => format!(
                "__w::offset(b, {}, &[{list}], {})",
                layout.head,
                object.optional_count()
            ),
        };
        let mut k = 0;
        for (field, slot) in object.fields.iter().zip(&layout.fields) {
            out.line("");
            let ty = self.view_ty(&field.ty, object.module, lt);
            let ty = if field.optional {
                format!("{OPTION}<{ty}>")
            } else {
                ty
            };
            out.line(format!(
                "pub fn {}(&self) -> {ty} {{",
                accessor(&field.name)
            ));
            out.line(format!(
                "let b: &{} [u8] = {bytes};",
                lt.trim_start_matches("'_")
            ));
            match *slot {
                Slot::Bit(bit) => out.line(format!("__w::bit(b, {bit})")),
                Slot::OptionalBit { presence, value } => {
                    out.line(format!("if __w::bit(b, {presence}) {{"));
                    out.line(format!("Some(__w::bit(b, {value}))"));
                    out.line("} else {");
                    out.line("None");
                    out.line("}");
                }
                Slot::At(at) => {
                    let cell = self.cell(&field.ty, object.module);
                    out.line(format!("unsafe {{ __w::read::<{cell}>(b, {at}) }}"));
                }
                Slot::Optional { presence } => {
                    let cell = self.cell(&field.ty, object.module);
                    out.line(format!("if __w::bit(b, {presence}) {{"));
                    out.line(format!(
                        "let at = __w::offset(b, {}, &[{optionals}], {k});",
                        layout.head
                    ));
                    out.line(format!("Some(unsafe {{ __w::read::<{cell}>(b, at) }})"));
                    out.line("} else {");
                    out.line("None");
                    out.line("}");
                    k += 1;
                }
                Slot::Var { slot, presence } => {
                    let var = self.var_view(&field.ty, object.module, lt);
                    let read = [
                        format!(
                            "let range = __w::slot(b, {start}, {}, {}, {}, {slot});",
                            layout.boundaries,
                            layout.boundary.bytes(),
                            layout.vars
                        ),
                        format!("unsafe {{ <{var} as __w::Var<'a>>::read(&b[range]) }}"),
                    ];
                    match presence {
                        Some(presence) => {
                            out.line(format!("if __w::bit(b, {presence}) {{"));
                            out.line(read[0].clone());
                            out.line(format!("Some({})", read[1]));
                            out.line("} else {");
                            out.line("None");
                            out.line("}");
                        }
                        None => {
                            out.line(read[0].clone());
                            out.line(read[1].clone());
                        }
                    }
                }
            }
            out.line("}");
        }
        out.line("}");

        out.line("");
        out.line(format!(
            "impl __w::Validate for {} {{",
            if fixed.is_some() {
                view.clone()
            } else {
                format!("{view}<'_>")
            }
        ));
        out.line(format!(
            "fn validate_at(buf: &[u8], at: usize) -> {RESULT}<(), __w::DecodeError> {{"
        ));
        self.validate(out, object);
        out.line("Ok(())");
        out.line("}");
        out.line("}");

        out.line("");
        match fixed {
            Some(_) => {
                out.line(format!("unsafe impl __w::Cell for {view} {{"));
                out.line(format!("type Value<'a> = &'a {view};"));
                out.line("");
                out.line(format!("fn get(&self) -> &{view} {{"));
                out.line("self");
                out.line("}");
                out.line("}");
                out.line("");
                out.line(format!("impl<'a> __w::Decode<'a> for &'a {view} {{"));
                out.line(format!(
                    "fn decode(buf: &'a [u8]) -> {RESULT}<Self, __w::DecodeError> {{"
                ));
                out.line(format!("{view}::decode(buf)"));
                out.line("}");
                out.line("}");
            }
            None => {
                out.line(format!("impl<'a> __w::Var<'a> for {view}<'a> {{"));
                out.line("unsafe fn read(bytes: &'a [u8]) -> Self {");
                out.line(format!("{view} {{ buf: bytes }}"));
                out.line("}");
                out.line("}");
                out.line("");
                out.line(format!("impl<'a> __w::Decode<'a> for {view}<'a> {{"));
                out.line(format!(
                    "fn decode(buf: &'a [u8]) -> {RESULT}<Self, __w::DecodeError> {{"
                ));
                out.line(format!("{view}::decode(buf)"));
                out.line("}");
                out.line("}");
            }
        }

        out.line("");
        out.line(format!(
            "impl ::core::fmt::Debug for {} {{",
            if fixed.is_some() {
                view.clone()
            } else {
                format!("{view}<'_>")
            }
        ));
        out.line("fn fmt(&self, f: &mut ::core::fmt::Formatter<'_>) -> ::core::fmt::Result {");
        out.line(format!("f.debug_struct({view:?})"));
        for field in object.fields {
            out.line(format!(
                ".field({:?}, &self.{}())",
                field.name,
                accessor(&field.name)
            ));
        }
        out.line(".finish()");
        out.line("}");
        out.line("}");
    }

    /// The body of `validate_at`: checks `buf`, exactly one encoding, that
    /// starts `at` bytes into the message.
    fn validate(&self, out: &mut Out, object: &Object) {
        let layout = object.layout;
        let name = format!("{:?}", object.name);
        let fixed = layout.size.fixed().is_some();
        if fixed {
            out.line(format!(
                "__w::de::exact(buf, {}, at, {name})?;",
                layout.head
            ));
        } else {
            out.line(format!(
                "__w::de::at_least(buf, {}, at, {name})?;",
                layout.head
            ));
        }

        let bits = layout
            .fields
            .iter()
            .map(|slot| match slot {
                Slot::Bit(bit) | Slot::Optional { presence: bit } => bit + 1,
                Slot::OptionalBit { value, .. } => value + 1,
                Slot::Var {
                    presence: Some(bit),
                    ..
                } => bit + 1,
                Slot::At(_) | Slot::Var { presence: None, .. } => 0,
            })
            .max()
            .unwrap_or(0);
        if !bits.is_multiple_of(8) {
            let last = layout.bitmap - 1;
            let mask = 0xffu8 << (bits % 8);
            out.line(format!(
                "__w::de::unused(buf[{last}], 0x{mask:02x}, at + {last}, {name})?;"
            ));
        }
        for (field, slot) in object.fields.iter().zip(&layout.fields) {
            if let Slot::OptionalBit { presence, value } = slot {
                out.line(format!(
                    "__w::de::option_bool(buf, {presence}, {value}, at, {:?})?;",
                    object.field(field)
                ));
            }
        }
        for (field, slot) in object.fields.iter().zip(&layout.fields) {
            if let Slot::At(offset) = *slot {
                let check = self.check_fixed(&field.ty, &object.field(field), object.module);
                if !check.is_empty() {
                    let end = offset + self.fixed_size(&field.ty);
                    out.line("{");
                    out.line(format!(
                        "let (b, at) = (&buf[{offset}..{end}], at + {offset});"
                    ));
                    out.extend(check);
                    out.line("}");
                }
            }
        }
        if fixed {
            return;
        }

        let vars = layout.vars as usize;
        let mut slots = Vec::new();
        for (field, slot) in object.fields.iter().zip(&layout.fields) {
            if let Slot::Var { slot, presence } = *slot {
                let check = self.check_var(&field.ty, &object.field(field), object.module);
                slots.push((slot as usize, presence, check, object.field(field)));
            }
        }
        // `pos`, where the var section starts, is read unless only one slot
        // without checks follows.
        let read = vars != 1
            || slots
                .iter()
                .any(|(_, presence, check, _)| presence.is_some() || !check.is_empty());
        if object.optional_count() > 0 {
            out.line(format!("let mut pos = {};", layout.head));
            for (field, slot) in object.fields.iter().zip(&layout.fields) {
                let Slot::Optional { presence } = *slot else {
                    continue;
                };
                let label = object.field(field);
                let size = self.fixed_size(&field.ty);
                out.line(format!("if __w::bit(buf, {presence}) {{"));
                out.line(format!(
                    "__w::de::at_least(buf, pos + {size}, at, {label:?})?;"
                ));
                let check = self.check_fixed(&field.ty, &label, object.module);
                if !check.is_empty() {
                    out.line("{");
                    out.line(format!(
                        "let (b, at) = (&buf[pos..pos + {size}], at + pos);"
                    ));
                    out.extend(check);
                    out.line("}");
                }
                out.line(format!("pos += {size};"));
                out.line("}");
            }
            if !read {
                out.line("let _ = pos;");
            }
        } else if read {
            out.line(format!("let pos = {};", layout.head));
        }
        if vars == 0 {
            out.line(format!("__w::de::exact(buf, pos, at, {name})?;"));
        }
        if vars > 1 {
            out.line(format!(
                "let ends = __w::de::boundaries::<{}>(buf, {}, {}, pos, at, {name})?;",
                vars - 1,
                layout.boundaries,
                layout.boundary.bytes()
            ));
        }
        for (slot, presence, check, label) in slots {
            if presence.is_none() && check.is_empty() {
                continue;
            }
            let start = if slot == 0 {
                "pos".to_string()
            } else {
                format!("ends[{}]", slot - 1)
            };
            let end = if slot + 1 == vars {
                "buf.len()".to_string()
            } else {
                format!("ends[{slot}]")
            };
            out.line("{");
            out.line(format!(
                "let (b, at) = (&buf[{start}..{end}], at + {start});"
            ));
            match presence {
                Some(presence) => {
                    out.line(format!("if __w::bit(buf, {presence}) {{"));
                    out.extend(check);
                    out.line("} else {");
                    out.line(format!("__w::de::empty(b, at, {label:?})?;"));
                    out.line("}");
                }
                None => out.extend(check),
            }
            out.line("}");
        }
    }

    /// Checks `b`, the bytes of a fixed-size `ty` starting `at` bytes into
    /// the message, beyond their size; empty when any bytes will do.
    fn check_fixed(&self, ty: &Type, raw: &str, module: &[String]) -> Vec<String> {
        let label = format!("{raw:?}");
        if let Some(int) = IntInfo::of(ty) {
            return match int.repr {
                Int::Native(_) if int.constrained() => vec![format!(
                    "__w::de::range(__w::de::plain::<{}>(b, 0), {}, {}, at, {label})?;",
                    int.cell(),
                    int.lit(int.lo),
                    int.lit(int.hi)
                )],
                Int::Biased { width, .. } if int.span() < width_max(width) => vec![format!(
                    "__w::de::range(__w::de::plain::<{}>(b, 0), 0, {}, at, {label})?;",
                    stored(width),
                    int.span()
                )],
                _ => Vec::new(),
            };
        }
        match &ty.kind {
            TypeKind::F32 | TypeKind::F64 => match float_args(ty) {
                Some(args) => vec![format!(
                    "__w::de::float(__w::de::plain::<{}>(b, 0), {args}, at, {label})?;",
                    self.cell(ty, module)
                )],
                None => Vec::new(),
            },
            TypeKind::Bool => vec![format!("__w::de::boolean(b[0], at, {label})?;")],
            TypeKind::Entity => vec![format!("__w::de::entity(b, at, {label})?;")],
            TypeKind::String => vec![format!("__w::de::utf8(b, at, {label})?;")],
            TypeKind::Array(item, len) => {
                let check = self.check_fixed(item, raw, module);
                if check.is_empty() {
                    return check;
                }
                let size = self.fixed_size(item);
                let mut lines = vec![
                    format!("for i in 0..{len} {{"),
                    format!("let (b, at) = (&b[i * {size}..(i + 1) * {size}], at + i * {size});"),
                ];
                lines.extend(check);
                lines.push("}".to_string());
                lines
            }
            TypeKind::Named(id) => match self.schema.def(*id).kind {
                DefKind::Enum(_) => vec![format!(
                    "__w::de::enumeration::<{}>(b, at, {label})?;",
                    self.path(*id, module, &self.names[id.0])
                )],
                _ if self.is_checked(*id) => vec![format!(
                    "<{} as __w::Validate>::validate_at(b, at)?;",
                    self.view_path(*id, module)
                )],
                _ => Vec::new(),
            },
            _ => Vec::new(),
        }
    }

    /// Checks `b`, exactly the bytes of a variable-size `ty` starting `at`
    /// bytes into the message; empty when any bytes will do.
    fn check_var(&self, ty: &Type, label: &str, module: &[String]) -> Vec<String> {
        let quoted = format!("{label:?}");
        let length = length_args(&ty.constraints);
        let mut lines = Vec::new();
        match &ty.kind {
            TypeKind::String | TypeKind::Bytes => {
                if ty.kind == TypeKind::String {
                    lines.push(format!("__w::de::utf8(b, at, {quoted})?;"));
                }
                if let Some(args) = length {
                    lines.push(format!("__w::de::length(b.len(), {args}, at, {quoted})?;"));
                }
            }
            TypeKind::Vec(_) | TypeKind::Set(_) | TypeKind::Map(..) => {
                let (key, item) = match &ty.kind {
                    TypeKind::Map(key, value) => (Some(&**key), &**value),
                    TypeKind::Vec(item) | TypeKind::Set(item) => (None, &**item),
                    _ => unreachable!(),
                };
                let key_size = key.map_or(0, |key| self.fixed_size(key));
                let (count, body) = match self.wire.sequence(ty).expect("a sequence") {
                    Sequence::Packed { item: size } => {
                        let mut body = Vec::new();
                        let fixed_item = |at: &str, ty: &Type, body: &mut Vec<String>| {
                            let check = self.check_fixed(ty, label, module);
                            if !check.is_empty() {
                                body.push("{".to_string());
                                body.push(at.to_string());
                                body.extend(check);
                                body.push("}".to_string());
                            }
                        };
                        if let Some(key) = key {
                            fixed_item(
                                &format!("let (b, at) = (&b[..{key_size}], at);"),
                                key,
                                &mut body,
                            );
                            fixed_item(
                                &format!("let (b, at) = (&b[{key_size}..], at + {key_size});"),
                                item,
                                &mut body,
                            );
                        } else {
                            body = self.check_fixed(item, label, module);
                        }
                        let mut looped = Vec::new();
                        if !body.is_empty() {
                            looped.push("for i in 0..n {".to_string());
                            looped.push(format!(
                                "let (b, at) = (&b[i * {size}..(i + 1) * {size}], at + i * {size});"
                            ));
                            looped.extend(body);
                            looped.push("}".to_string());
                        }
                        (format!("__w::de::packed(b, {size}, at, {quoted})?"), looped)
                    }
                    Sequence::Counted { count } => (
                        format!("__w::de::counted(b, {}, at, {quoted})?", count.bytes()),
                        Vec::new(),
                    ),
                    Sequence::Prefixed { count, prefix } => {
                        let mut check = Vec::new();
                        if let Some(key) = key {
                            check.push(format!("__w::de::at_least(b, {key_size}, at, {quoted})?;"));
                            let key_check = self.check_fixed(key, label, module);
                            if !key_check.is_empty() {
                                check.push("{".to_string());
                                check.push(format!("let (b, at) = (&b[..{key_size}], at);"));
                                check.extend(key_check);
                                check.push("}".to_string());
                            }
                            let value_check = self.check_var(item, label, module);
                            if !value_check.is_empty() {
                                check.push("{".to_string());
                                check.push(format!(
                                    "let (b, at) = (&b[{key_size}..], at + {key_size});"
                                ));
                                check.extend(value_check);
                                check.push("}".to_string());
                            }
                        } else {
                            check = self.check_var(item, label, module);
                        }
                        let call = if check.is_empty() {
                            format!(
                                "__w::de::prefixed(b, {}, {}, at, {quoted}, |_, _| Ok(()))?",
                                count.bytes(),
                                prefix.bytes()
                            )
                        } else {
                            let mut call = format!(
                                "__w::de::prefixed(b, {}, {}, at, {quoted}, |b, at| {{\n",
                                count.bytes(),
                                prefix.bytes()
                            );
                            for line in check {
                                call.push_str(&line);
                                call.push('\n');
                            }
                            call.push_str("Ok(())\n})?");
                            call
                        };
                        (call, Vec::new())
                    }
                };
                // Single bytes always fill their range.
                let trivial = matches!(self.wire.sequence(ty), Some(Sequence::Packed { item: 1 }));
                if length.is_some() || !body.is_empty() {
                    lines.push(format!("let n = {count};"));
                } else if !trivial {
                    lines.push(format!("{count};"));
                }
                if let Some(args) = length {
                    lines.push(format!("__w::de::length(n, {args}, at, {quoted})?;"));
                }
                lines.extend(body);
            }
            TypeKind::Named(id) => lines.push(format!(
                "<{}<'_> as __w::Validate>::validate_at(b, at)?;",
                self.view_path(*id, module)
            )),
            _ => unreachable!("only strings, bytes, collections, and structs vary in size"),
        }
        lines
    }

    /// Whether a fixed-size struct needs checks beyond its size.
    fn is_checked(&self, id: TypeId) -> bool {
        if let Some(checked) = self.checked.borrow()[id.0] {
            return checked;
        }
        let layout = self.wire.layout(id);
        let fields = match &self.schema.def(id).kind {
            DefKind::Struct(item) => &item.fields,
            DefKind::Message(item) => &item.fields,
            DefKind::Enum(_) => unreachable!("enums are checked as enums"),
        };
        let bits: u32 = layout
            .fields
            .iter()
            .map(|slot| match slot {
                Slot::Bit(_) => 1,
                Slot::OptionalBit { .. } => 2,
                _ => 0,
            })
            .sum();
        let module = &self.modules[id.0];
        let checked = !bits.is_multiple_of(8)
            || layout
                .fields
                .iter()
                .any(|slot| matches!(slot, Slot::OptionalBit { .. }))
            || fields.iter().zip(&layout.fields).any(|(field, slot)| {
                matches!(slot, Slot::At(_)) && !self.check_fixed(&field.ty, "", module).is_empty()
            });
        self.checked.borrow_mut()[id.0] = Some(checked);
        checked
    }

    /// The `(presence, size)` list of an object's optional fixed-size
    /// fields, as `__w::offset` takes it.
    fn optionals(&self, object: &Object) -> String {
        let optionals: Vec<String> = object
            .fields
            .iter()
            .zip(&object.layout.fields)
            .filter_map(|(field, slot)| match slot {
                Slot::Optional { presence } => {
                    Some(format!("({presence}, {})", self.fixed_size(&field.ty)))
                }
                _ => None,
            })
            .collect();
        optionals.join(", ")
    }

    // -----------------------------------------------------------------------
    // Types

    /// `name`, declared in `id`'s module, as seen from `module`.
    fn path(&self, id: TypeId, module: &[String], name: &str) -> String {
        let target = &self.modules[id.0];
        let common = target
            .iter()
            .zip(module)
            .take_while(|(left, right)| left == right)
            .count();
        let up = module.len() - common;
        let mut path = match (up, common == target.len()) {
            (0, true) => String::new(),
            // `self::` keeps a module from being read as a crate.
            (0, false) => "self::".to_string(),
            _ => "super::".repeat(up),
        };
        for segment in &target[common..] {
            path.push_str(segment);
            path.push_str("::");
        }
        path.push_str(name);
        path
    }

    fn view_path(&self, id: TypeId, module: &[String]) -> String {
        self.path(id, module, &format!("{}View", self.names[id.0]))
    }

    fn is_fixed_def(&self, id: TypeId) -> bool {
        match self.schema.def(id).kind {
            DefKind::Enum(_) => true,
            _ => self.wire.layout(id).size.fixed().is_some(),
        }
    }

    fn fixed_size(&self, ty: &Type) -> u32 {
        self.wire.size(ty).fixed().expect("a fixed-size type")
    }

    fn field_owned(&self, field: &Field, module: &[String]) -> String {
        let ty = self.owned(&field.ty, module);
        if field.optional {
            format!("{OPTION}<{ty}>")
        } else {
            ty
        }
    }

    /// The owned Rust type of `ty`.
    fn owned(&self, ty: &Type, module: &[String]) -> String {
        if let Some(int) = IntInfo::of(ty) {
            return int.rust.to_string();
        }
        match &ty.kind {
            TypeKind::F32 => "f32".to_string(),
            TypeKind::F64 => "f64".to_string(),
            TypeKind::Bool => "bool".to_string(),
            TypeKind::Entity => "__w::Entity".to_string(),
            TypeKind::String => STRING.to_string(),
            TypeKind::Bytes => match ty.constraints.fixed_length() {
                Some(len) => format!("[u8; {len}]"),
                None => format!("{VEC}<u8>"),
            },
            TypeKind::Array(item, len) => format!("[{}; {len}]", self.owned(item, module)),
            TypeKind::Vec(item) => format!("{VEC}<{}>", self.owned(item, module)),
            TypeKind::Set(item) => {
                format!("::std::collections::HashSet<{}>", self.owned(item, module))
            }
            TypeKind::Map(key, value) => format!(
                "::std::collections::HashMap<{}, {}>",
                self.owned(key, module),
                self.owned(value, module)
            ),
            TypeKind::Named(id) => self.path(*id, module, &self.names[id.0]),
            _ => unreachable!("integers are handled above"),
        }
    }

    /// The cell a fixed-size `ty` is read through.
    fn cell(&self, ty: &Type, module: &[String]) -> String {
        if let Some(int) = IntInfo::of(ty) {
            return int.cell();
        }
        match &ty.kind {
            TypeKind::F32 => "__w::F32".to_string(),
            TypeKind::F64 => "__w::F64".to_string(),
            TypeKind::Bool => "__w::Bool".to_string(),
            TypeKind::Entity => "__w::EntityCell".to_string(),
            TypeKind::String => format!("__w::FixedStr<{}>", self.fixed_size(ty)),
            TypeKind::Bytes => format!("[u8; {}]", self.fixed_size(ty)),
            TypeKind::Array(item, len) => format!("[{}; {len}]", self.cell(item, module)),
            TypeKind::Named(id) => match self.schema.def(*id).kind {
                DefKind::Enum(_) => format!(
                    "__w::EnumCell<{}>",
                    self.path(*id, module, &self.names[id.0])
                ),
                _ => self.view_path(*id, module),
            },
            _ => unreachable!("only fixed-size types have cells"),
        }
    }

    /// What reading `ty` in place gives, borrowing for `lt`.
    fn view_ty(&self, ty: &Type, module: &[String], lt: &str) -> String {
        if self.wire.size(ty).fixed().is_none() {
            return self.var_view(ty, module, lt);
        }
        if let Some(int) = IntInfo::of(ty) {
            return int.rust.to_string();
        }
        match &ty.kind {
            TypeKind::String => format!("&{lt} str"),
            TypeKind::Bytes => format!("&{lt} [u8; {}]", self.fixed_size(ty)),
            TypeKind::Array(..) => format!("&{lt} {}", self.cell(ty, module)),
            TypeKind::Named(id) => match self.schema.def(*id).kind {
                DefKind::Enum(_) => self.path(*id, module, &self.names[id.0]),
                _ => format!("&{lt} {}", self.view_path(*id, module)),
            },
            _ => self.owned(ty, module),
        }
    }

    /// The view of a variable-size `ty`.
    fn var_view(&self, ty: &Type, module: &[String], lt: &str) -> String {
        match &ty.kind {
            TypeKind::String => format!("&{lt} str"),
            TypeKind::Bytes => format!("&{lt} [u8]"),
            TypeKind::Vec(item) | TypeKind::Set(item) => {
                match self.wire.sequence(ty).expect("a sequence") {
                    Sequence::Packed { .. } => {
                        format!("__w::Packed<{lt}, {}>", self.cell(item, module))
                    }
                    Sequence::Counted { count } => format!(
                        "__w::Counted<{lt}, {}, {}>",
                        self.cell(item, module),
                        count.bytes()
                    ),
                    Sequence::Prefixed { count, prefix } => format!(
                        "__w::Prefixed<{lt}, {}, {}, {}>",
                        self.view_ty(item, module, lt),
                        count.bytes(),
                        prefix.bytes()
                    ),
                }
            }
            TypeKind::Map(key, value) => {
                let entry = || {
                    format!(
                        "__w::Entry<{}, {}>",
                        self.cell(key, module),
                        self.cell(value, module)
                    )
                };
                match self.wire.sequence(ty).expect("a sequence") {
                    Sequence::Packed { .. } => format!("__w::Packed<{lt}, {}>", entry()),
                    Sequence::Counted { count } => {
                        format!("__w::Counted<{lt}, {}, {}>", entry(), count.bytes())
                    }
                    Sequence::Prefixed { count, prefix } => format!(
                        "__w::PrefixedMap<{lt}, {}, {}, {}, {}>",
                        self.cell(key, module),
                        self.view_ty(value, module, lt),
                        count.bytes(),
                        prefix.bytes()
                    ),
                }
            }
            TypeKind::Named(id) => format!("{}<{lt}>", self.view_path(*id, module)),
            _ => unreachable!("only strings, bytes, collections, and structs vary in size"),
        }
    }

    /// Converts `e`, a value read in place as `ty`, to the owned type.
    fn owned_from(&self, ty: &Type, e: &str) -> String {
        match &ty.kind {
            TypeKind::String => format!("{STRING}::from({e})"),
            TypeKind::Bytes => match ty.constraints.fixed_length() {
                Some(_) => format!("*{e}"),
                None => format!("{e}.to_vec()"),
            },
            TypeKind::Array(item, _) => {
                if is_raw_byte(item) || IntInfo::of(item).is_some_and(|int| int.rust == "i8") {
                    format!("*{e}")
                } else {
                    let item = self.owned_from(item, "__w::Cell::get(c)");
                    format!("{e}.each_ref().map(|c| {item})")
                }
            }
            TypeKind::Vec(item) | TypeKind::Set(item) => {
                if matches!(ty.kind, TypeKind::Vec(_))
                    && is_raw_byte(item)
                    && matches!(self.wire.sequence(ty), Some(Sequence::Packed { .. }))
                {
                    return format!("{e}.as_slice().to_vec()");
                }
                match self.owned_from(item, "v").as_str() {
                    "v" => format!("{e}.iter().collect()"),
                    item => format!("{e}.iter().map(|v| {item}).collect()"),
                }
            }
            TypeKind::Map(key, value) => {
                let key = self.owned_from(key, "k");
                let value = self.owned_from(value, "v");
                if key == "k" && value == "v" {
                    format!("{e}.iter().collect()")
                } else {
                    format!("{e}.iter().map(|(k, v)| ({key}, {value})).collect()")
                }
            }
            TypeKind::Named(id) => match self.schema.def(*id).kind {
                DefKind::Enum(_) => e.to_string(),
                _ => format!("{e}.to_owned()"),
            },
            _ => e.to_string(),
        }
    }
}

/// A struct or message being emitted.
struct Object<'a> {
    /// The name errors report, as `Outer.Inner`.
    name: String,
    layout: &'a Layout,
    fields: &'a [Field],
    module: &'a [String],
}

impl Object<'_> {
    fn field(&self, field: &Field) -> String {
        format!("{}.{}", self.name, field.name)
    }

    fn optional_count(&self) -> usize {
        self.layout
            .fields
            .iter()
            .filter(|slot| matches!(slot, Slot::Optional { .. }))
            .count()
    }
}

#[derive(Default)]
struct Module {
    defs: Vec<TypeId>,
    consts: Vec<ConstId>,
    children: BTreeMap<String, Module>,
    /// A namespace, or one enclosing a namespace, emitted as its own file;
    /// the modules of nested types are inline.
    file: bool,
}

/// Lines of Rust, indented by brace depth when finished.
#[derive(Default)]
struct Out {
    lines: Vec<String>,
}

impl Out {
    fn line(&mut self, line: impl Into<String>) {
        let line = line.into();
        // Multi-line pieces, such as closures built as one string.
        for part in line.split('\n') {
            // No blank line opens a block.
            let opens = self.lines.last().is_some_and(|last| last.ends_with('{'));
            if part.is_empty() && opens {
                continue;
            }
            self.lines.push(part.to_string());
        }
    }

    fn extend(&mut self, lines: Vec<String>) {
        for line in lines {
            self.line(line);
        }
    }

    /// Indents each line one level per line that left brackets open, as
    /// rustfmt does: `f(x, |y| {` indents its body once, not twice.
    fn finish(self) -> String {
        let mut out = String::new();
        // How many brackets each open level still holds.
        let mut levels: Vec<usize> = Vec::new();
        for line in &self.lines {
            let line = line.trim();
            if line.is_empty() {
                out.push('\n');
                continue;
            }
            let mut indent = None;
            let mut pushed = false;
            let mut in_string = false;
            let mut escaped = false;
            for ch in line.chars() {
                if in_string {
                    match ch {
                        _ if escaped => escaped = false,
                        '\\' => escaped = true,
                        '"' => in_string = false,
                        _ => {}
                    }
                    continue;
                }
                // The first character that isn't a closer fixes the indent.
                if !matches!(ch, '}' | ')' | ']') {
                    indent.get_or_insert(levels.len());
                }
                match ch {
                    '"' => in_string = true,
                    '{' | '(' | '[' => match levels.last_mut() {
                        Some(count) if pushed => *count += 1,
                        _ => {
                            levels.push(1);
                            pushed = true;
                        }
                    },
                    '}' | ')' | ']' => {
                        if let Some(count) = levels.last_mut() {
                            *count -= 1;
                            if *count == 0 {
                                levels.pop();
                                pushed = false;
                            }
                        }
                    }
                    _ => {}
                }
            }
            let indent = indent.unwrap_or(levels.len());
            for _ in 0..indent {
                out.push_str("    ");
            }
            out.push_str(line);
            out.push('\n');
        }
        out
    }
}

/// Rejects types the Rust runtime has no values for yet.
fn unsupported(schema: &Schema) -> Result<(), Error> {
    fn find(ty: &Type) -> Option<&'static str> {
        match &ty.kind {
            TypeKind::Timestamp => Some("timestamp"),
            TypeKind::Interval => Some("interval"),
            TypeKind::UEntity => Some("uentity"),
            TypeKind::Uuid => Some("uuid"),
            TypeKind::Array(item, _) | TypeKind::Vec(item) | TypeKind::Set(item) => find(item),
            TypeKind::Map(key, value) => find(key).or_else(|| find(value)),
            _ => None,
        }
    }
    let mut errors = Vec::new();
    for (index, def) in schema.defs.iter().enumerate() {
        let fields = match &def.kind {
            DefKind::Enum(_) => continue,
            DefKind::Struct(item) => &item.fields,
            DefKind::Message(item) => &item.fields,
        };
        for field in fields {
            if let Some(name) = find(&field.ty) {
                errors.push(format!(
                    "`{}.{}`: the Rust backend does not support `{name}` yet",
                    schema.qualified(TypeId(index)),
                    field.name
                ));
            }
        }
    }
    if !errors.is_empty() {
        return Err(Error::new(errors.join("\n")));
    }
    Ok(())
}

/// The module `id` is declared in: its namespace's, then one per enclosing
/// declaration, so `a.Foo.Bar` lives in `a::foo`.
fn module(schema: &Schema, id: TypeId) -> Vec<String> {
    let def = schema.def(id);
    scope_module(schema, def.namespace, def.parent)
}

/// The module of what is declared in `parent`, or at the top of
/// `namespace`.
fn scope_module(schema: &Schema, namespace: NamespaceId, parent: Option<TypeId>) -> Vec<String> {
    match parent {
        Some(parent) => {
            let mut module = module(schema, parent);
            module.push(snake(&schema.def(parent).name));
            module
        }
        None => {
            let namespace = schema.namespace(namespace);
            namespace.name.iter().map(|name| ident(name)).collect()
        }
    }
}

/// Each const's name in `SCREAMING_SNAKE_CASE`: `MaxHp` is `MAX_HP`. A
/// name made only of underscores has no words to convert and is rejected.
fn const_names(schema: &Schema) -> Result<Vec<String>, Error> {
    let mut names = Vec::with_capacity(schema.consts.len());
    let mut errors = Vec::new();
    for (index, item) in schema.consts.iter().enumerate() {
        let name = case::shouty(&item.name);
        if name.is_empty() {
            errors.push(format!(
                "`{}` has no words to name a Rust constant",
                schema.const_qualified(ConstId(index))
            ));
        }
        // `_1` is `1`, which must not start an identifier.
        if name.starts_with(|ch: char| ch.is_ascii_digit()) {
            names.push(format!("_{name}"));
        } else {
            names.push(name);
        }
    }
    if !errors.is_empty() {
        return Err(Error::new(errors.join("\n")));
    }
    Ok(names)
}

/// `value` as a Rust string literal. Escaped by hand rather than with
/// `{:?}`, whose choices may change between Rust versions and churn
/// committed code.
fn string_literal(value: &str) -> String {
    let mut out = String::from("\"");
    for ch in value.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '\0' => out.push_str("\\0"),
            ch if ch.is_control() => out.push_str(&format!("\\u{{{:x}}}", ch as u32)),
            ch => out.push(ch),
        }
    }
    out.push('"');
    out
}

/// Every declaration's role: whether this peer encodes it, and whether it
/// decodes it. Structs no message reaches get both.
fn roles(schema: &Schema, direction: Option<Direction>) -> (Vec<bool>, Vec<bool>) {
    let len = schema.defs.len();
    let Some(direction) = direction else {
        return (vec![true; len], vec![true; len]);
    };
    let mut encode = vec![false; len];
    let mut decode = vec![false; len];

    fn mark(
        schema: &Schema,
        id: TypeId,
        roles: (bool, bool),
        encode: &mut [bool],
        decode: &mut [bool],
    ) {
        let (enc, dec) = roles;
        if (!enc || encode[id.0]) && (!dec || decode[id.0]) {
            return;
        }
        encode[id.0] |= enc;
        decode[id.0] |= dec;
        let fields = match &schema.def(id).kind {
            DefKind::Struct(item) => &item.fields,
            DefKind::Message(item) => &item.fields,
            DefKind::Enum(_) => return,
        };
        for field in fields {
            let mut named = Vec::new();
            named_in(&field.ty, &mut named);
            for inner in named {
                mark(schema, inner, roles, encode, decode);
            }
        }
    }

    for (index, def) in schema.defs.iter().enumerate() {
        if let DefKind::Message(item) = &def.kind {
            let roles = match (direction, item.direction) {
                (_, Direction::Bi) => (true, true),
                (peer, way) if peer == way => (false, true),
                _ => (true, false),
            };
            mark(schema, TypeId(index), roles, &mut encode, &mut decode);
        }
    }
    for (index, def) in schema.defs.iter().enumerate() {
        let reached = encode[index] || decode[index];
        if !reached && !matches!(def.kind, DefKind::Message(_)) {
            mark(
                schema,
                TypeId(index),
                (true, true),
                &mut encode,
                &mut decode,
            );
        }
    }
    (encode, decode)
}

fn named_in(ty: &Type, out: &mut Vec<TypeId>) {
    match &ty.kind {
        TypeKind::Array(item, _) | TypeKind::Vec(item) | TypeKind::Set(item) => named_in(item, out),
        TypeKind::Map(key, value) => {
            named_in(key, out);
            named_in(value, out);
        }
        TypeKind::Named(id) => out.push(*id),
        _ => {}
    }
}

/// The traits each owned type derives: what all of its fields support,
/// assuming recursive types support everything until shown otherwise.
fn traits(schema: &Schema) -> Vec<Traits> {
    let mut traits = vec![ALL; schema.defs.len()];
    loop {
        let mut changed = false;
        for (index, def) in schema.defs.iter().enumerate() {
            let fields = match &def.kind {
                DefKind::Enum(_) => continue,
                DefKind::Struct(item) => &item.fields,
                DefKind::Message(item) => &item.fields,
            };
            let mut all = ALL;
            for field in fields {
                let field_traits = type_traits(&field.ty, &traits);
                all.eq &= field_traits.eq;
                all.hash &= field_traits.hash;
                all.default &= field.optional || field_traits.default;
                all.copy &= field_traits.copy;
            }
            if all != traits[index] {
                traits[index] = all;
                changed = true;
            }
        }
        if !changed {
            return traits;
        }
    }
}

fn type_traits(ty: &Type, traits: &[Traits]) -> Traits {
    match &ty.kind {
        TypeKind::F32 | TypeKind::F64 => Traits {
            eq: false,
            hash: false,
            ..ALL
        },
        // The runtime's identities have no default.
        TypeKind::Entity => Traits {
            default: false,
            ..ALL
        },
        TypeKind::String => Traits { copy: false, ..ALL },
        TypeKind::Bytes => match ty.constraints.fixed_length() {
            Some(len) => Traits {
                default: len <= 32,
                ..ALL
            },
            None => Traits { copy: false, ..ALL },
        },
        // `Default` covers arrays of up to 32 items.
        TypeKind::Array(item, len) => Traits {
            default: type_traits(item, traits).default && *len <= 32,
            ..type_traits(item, traits)
        },
        TypeKind::Vec(item) => Traits {
            default: true,
            copy: false,
            ..type_traits(item, traits)
        },
        TypeKind::Set(item) => Traits {
            eq: type_traits(item, traits).eq,
            hash: false,
            default: true,
            copy: false,
        },
        TypeKind::Map(key, value) => Traits {
            eq: type_traits(key, traits).eq && type_traits(value, traits).eq,
            hash: false,
            default: true,
            copy: false,
        },
        TypeKind::Named(id) => traits[id.0],
        _ => ALL,
    }
}

/// An integer's Rust type, bounds, and wire representation.
struct IntInfo {
    rust: &'static str,
    lo: i128,
    hi: i128,
    min: i128,
    max: i128,
    repr: Int,
}

impl IntInfo {
    fn of(ty: &Type) -> Option<IntInfo> {
        let (rust, min, max) = match ty.kind {
            TypeKind::I8 => ("i8", i8::MIN as i128, i8::MAX as i128),
            TypeKind::I16 => ("i16", i16::MIN as i128, i16::MAX as i128),
            TypeKind::I32 => ("i32", i32::MIN as i128, i32::MAX as i128),
            TypeKind::I64 => ("i64", i64::MIN as i128, i64::MAX as i128),
            TypeKind::U8 => ("u8", 0, u8::MAX as i128),
            TypeKind::U16 => ("u16", 0, u16::MAX as i128),
            TypeKind::U32 => ("u32", 0, u32::MAX as i128),
            TypeKind::U64 => ("u64", 0, u64::MAX as i128),
            _ => return None,
        };
        let bound = |bound: Option<Number>, default| match bound {
            Some(Number::Int(value)) => value,
            _ => default,
        };
        Some(IntInfo {
            rust,
            lo: bound(ty.constraints.min, min),
            hi: bound(ty.constraints.max, max),
            min,
            max,
            repr: Int::of(ty)?,
        })
    }

    fn constrained(&self) -> bool {
        self.lo > self.min || self.hi < self.max
    }

    fn span(&self) -> u128 {
        (self.hi - self.lo) as u128
    }

    /// `value` as a literal of the declared type.
    fn lit(&self, value: i128) -> String {
        if value == self.min {
            format!("{}::MIN", self.rust)
        } else if value == self.max {
            format!("{}::MAX", self.rust)
        } else {
            value.to_string()
        }
    }

    fn cell(&self) -> String {
        match self.repr {
            Int::Native(_) => match self.rust {
                "u8" | "i8" => self.rust.to_string(),
                rust => format!("__w::{}", rust.to_uppercase()),
            },
            // A negative const argument needs braces.
            Int::Biased { min, width } if min < 0 => {
                format!("__w::Biased<{}, {}, {{ {min} }}>", self.rust, stored(width))
            }
            Int::Biased { min, width } => {
                format!("__w::Biased<{}, {}, {min}>", self.rust, stored(width))
            }
        }
    }
}

/// The cell holding a biased integer of `width`.
fn stored(width: Width) -> &'static str {
    match width {
        Width::U8 => "u8",
        Width::U16 => "__w::U16",
        Width::U32 => "__w::U32",
        Width::U64 => "__w::U64",
    }
}

fn unsigned(width: Width) -> &'static str {
    match width {
        Width::U8 => "u8",
        Width::U16 => "u16",
        Width::U32 => "u32",
        Width::U64 => "u64",
    }
}

fn width_max(width: Width) -> u128 {
    match width {
        Width::U8 => u8::MAX as u128,
        Width::U16 => u16::MAX as u128,
        Width::U32 => u32::MAX as u128,
        Width::U64 => u64::MAX as u128,
    }
}

/// A `u8` stored as itself, so a run of them is plain bytes.
fn is_raw_byte(ty: &Type) -> bool {
    IntInfo::of(ty).is_some_and(|int| {
        int.rust == "u8" && !int.constrained() && matches!(int.repr, Int::Native(_))
    })
}

/// The `nan, infinite, min, max` arguments of a float check, or `None` when
/// every value is allowed.
fn float_args(ty: &Type) -> Option<String> {
    let rust = match ty.kind {
        TypeKind::F32 => "f32",
        TypeKind::F64 => "f64",
        _ => return None,
    };
    let c = &ty.constraints;
    let bound = |bound: Option<Number>, default: &str| match bound {
        Some(Number::Float(value)) => format!("{value:?}"),
        Some(Number::Int(value)) => format!("{value}.0"),
        None => format!("{rust}::{default}"),
    };
    if c.nan && c.infinite && c.min.is_none() && c.max.is_none() {
        return None;
    }
    Some(format!(
        "{}, {}, {}, {}",
        c.nan,
        c.infinite,
        bound(c.min, "NEG_INFINITY"),
        bound(c.max, "INFINITY")
    ))
}

/// The `min, max` arguments of a length check, or `None` without
/// `min_length` or `max_length`.
fn length_args(c: &Constraints) -> Option<String> {
    if c.min_length.is_none() && c.max_length.is_none() {
        return None;
    }
    let max = c
        .max_length
        .map_or_else(|| "__w::MAX_SIZE".to_string(), |max| max.to_string());
    Some(format!("{}, {max}", c.min_length.unwrap_or(0)))
}

fn set_bit(bit: u32) -> String {
    format!("bits[{}] |= 0x{:02x};", bit / 8, 1u8 << (bit % 8))
}

/// `e.map(|v| inner)`, or `e` when `inner` is `v` itself.
fn optional(e: &str, inner: &str) -> String {
    if inner == "v" {
        e.to_string()
    } else {
        format!("{e}.map(|v| {inner})")
    }
}

/// `name` as a Rust identifier: raw for keywords, with a trailing `_` for
/// the few that cannot be raw.
fn ident(name: &str) -> String {
    const KEYWORDS: &[&str] = &[
        "abstract", "as", "async", "await", "become", "box", "break", "const", "continue", "do",
        "dyn", "else", "enum", "extern", "false", "final", "fn", "for", "gen", "if", "impl", "in",
        "let", "loop", "macro", "match", "mod", "move", "mut", "override", "priv", "pub", "ref",
        "return", "static", "struct", "trait", "true", "try", "type", "typeof", "unsafe",
        "unsized", "use", "virtual", "where", "while", "yield",
    ];
    if matches!(name, "self" | "Self" | "super" | "crate" | "_") {
        format!("{name}_")
    } else if KEYWORDS.contains(&name) {
        format!("r#{name}")
    } else {
        name.to_string()
    }
}

/// `name` in snake case as a Rust identifier, for a module: `MyResponse`
/// becomes `my_response`, and `Type` becomes `r#type`.
fn snake(name: &str) -> String {
    ident(&case::snake(name))
}

/// A field's accessor on a view, kept clear of the view's own methods.
fn accessor(name: &str) -> String {
    if VIEW_METHODS.contains(&name) {
        format!("{name}_")
    } else {
        ident(name)
    }
}

