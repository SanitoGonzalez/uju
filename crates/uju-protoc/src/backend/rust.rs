/// Where generated code finds the runtime, aliased as `__w` in each module.
const RUNTIME: &str = "::uju::net::wire";
/// The file each module is emitted into, in a directory named after it; the
/// root module's is at the top.
const FILE: &str = "mod.rs";
/// The first line of every file, holding [`MARKER`].
///
/// [`MARKER`]: crate::backend::MARKER
const HEADER: &str = "// @generated by `ujuc protocol rust`. Do not edit.";
/// Lints generated modules are exempt from.
const ALLOW: &str = "#[allow(non_camel_case_types, non_snake_case, missing_docs, clippy::all)]";

const RESULT: &str = "::core::result::Result";
const OPTION: &str = "::core::option::Option";
const STRING: &str = "::std::string::String";
const VEC: &str = "::std::vec::Vec";

/// View methods a field accessor must not shadow; such fields get a
/// trailing `_`.
const VIEW_METHODS: &[&str] = &[
    "decode",
    "decode_unchecked",
    "validate",
    "to_owned",
    "as_bytes",
];

pub struct Rust {
    /// The peer to generate, as in [`Options::direction`]. Types only one
    /// side needs get only that side: a server decodes `in` messages and
    /// encodes `out` ones.
    ///
    /// [`Options::direction`]: crate::backend::Options::direction
    pub direction: Option<Direction>,
}

impl Backend for Rust {
    fn generate(&self, schema: &Schema) -> Result<Vec<GeneratedFile>, Error> {
        let wire = backend::wire(schema)?;
        let direction = self
            .direction
            .filter(|direction| *direction != Direction::Bi);
        let generator = Generator::new(schema, &wire, direction)?;
        Ok(generator.files())
    }
}

