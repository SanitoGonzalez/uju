/// The traits an owned type can derive beyond `Debug`, `Clone`, and
/// `PartialEq`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct Traits {
    eq: bool,
    hash: bool,
    default: bool,
    copy: bool,
}

impl Traits {
    /// What both `self` and `other` support.
    fn and(self, other: Traits) -> Traits {
        Traits {
            eq: self.eq && other.eq,
            hash: self.hash && other.hash,
            default: self.default && other.default,
            copy: self.copy && other.copy,
        }
    }
}

const ALL: Traits = Traits {
    eq: true,
    hash: true,
    default: true,
    copy: true,
};

struct Generator<'a> {
    schema: &'a Schema,
    wire: &'a Wire,
    /// `None` for every role.
    role: Option<Role>,
    /// The Rust name of each declaration, indexed by [`TypeId`]: its path
    /// joined, as `MyResponseResult` for an enum nested in `MyResponse`.
    names: Vec<String>,
    /// The module each declaration lives in, as Rust identifiers.
    modules: Vec<Vec<String>>,
    /// The Rust name of each const, indexed by [`ConstId`], and the module
    /// it lives in.
    const_names: Vec<String>,
    const_modules: Vec<Vec<String>>,
    traits: Vec<Traits>,
    /// Whether each declaration is encoded, or decoded, by this role. A
    /// declaration doing neither is left out.
    encode: Vec<bool>,
    decode: Vec<bool>,
    /// Whether a fixed-size struct's bytes need checks beyond their size,
    /// filled in on demand.
    checked: RefCell<Vec<Option<bool>>>,
    /// Whether a union's view borrows the buffer, and so takes a lifetime,
    /// filled in on demand.
    borrows: RefCell<Vec<Option<bool>>>,
}

impl<'a> Generator<'a> {
    fn new(schema: &'a Schema, wire: &'a Wire, role: Option<Role>) -> Result<Generator<'a>, Error> {
        unsupported(schema)?;
        let len = schema.defs.len();
        let names = schema.defs.iter().map(|def| ident(&def.name)).collect();
        let modules = (0..len)
            .map(|index| module(schema, TypeId(index)))
            .collect();
        let const_names = const_names(schema)?;
        let const_modules = schema
            .consts
            .iter()
            .map(|item| scope_module(schema, item.namespace, item.parent))
            .collect();
        let (encode, decode) = roles(schema, role);
        let generator = Generator {
            schema,
            wire,
            role,
            names,
            modules,
            const_names,
            const_modules,
            traits: traits(schema),
            encode,
            decode,
            checked: RefCell::new(vec![None; len]),
            borrows: RefCell::new(vec![None; len]),
        };
        generator.check_names()?;
        Ok(generator)
    }

    /// Rejects declarations whose Rust names collide within a module, as
    /// `a.B` beside `a.BView`, or the module of `a.Foo`'s nested types beside
    /// a namespace `a.foo`.
    fn check_names(&self) -> Result<(), Error> {
        let mut seen: BTreeMap<(Vec<String>, String), String> = BTreeMap::new();
        let mut errors = Vec::new();
        // Consts are values, so they never meet a type, but `MaxHp` and
        // `MAXHp` are both `MAX_HP`.
        let mut values: BTreeMap<(&[String], &str), ConstId> = BTreeMap::new();
        for (index, name) in self.const_names.iter().enumerate() {
            let key = (&self.const_modules[index][..], name.as_str());
            if let Some(previous) = values.insert(key, ConstId(index)) {
                errors.push(format!(
                    "`{}` and `{}` both generate `{name}`",
                    self.schema.const_qualified(previous),
                    self.schema.const_qualified(ConstId(index))
                ));
            }
        }
        let mut claim = |module: &[String], name: String, owner: String| {
            let key = (module.to_vec(), name);
            match seen.get(&key) {
                Some(previous) if *previous != owner => errors.push(format!(
                    "`{previous}` and `{owner}` both generate `{}`",
                    key.1
                )),
                Some(_) => {}
                None => {
                    seen.insert(key, owner);
                }
            }
        };
        for namespace in &self.schema.namespaces {
            let segments: Vec<String> = namespace.name.iter().map(|name| ident(name)).collect();
            for depth in 1..=segments.len() {
                let owner = format!("namespace {}", namespace.name[..depth].join("."));
                claim(&segments[..depth - 1], segments[depth - 1].clone(), owner);
            }
        }
        for (index, def) in self.schema.defs.iter().enumerate() {
            let owner = self.schema.qualified(TypeId(index));
            let module = &self.modules[index];
            if let Some(parent) = def.parent {
                let (name, outer) = module.split_last().expect("nested in a module");
                let owner = format!("declarations nested in {}", self.schema.qualified(parent));
                claim(outer, name.clone(), owner);
            }
            claim(module, self.names[index].clone(), owner.clone());
            // A `type` is its own view.
            if !matches!(def.kind, DefKind::Enum(_) | DefKind::Type(_)) {
                claim(module, format!("{}View", self.names[index]), owner.clone());
            }
            if let DefKind::Union(item) = &def.kind
                && has_fields(item)
            {
                let owner = format!("the variant views of {owner}");
                claim(module, snake(&def.name), owner);
            }
        }
        for (index, item) in self.schema.consts.iter().enumerate() {
            if let Some(parent) = item.parent {
                let module = &self.const_modules[index];
                let (name, outer) = module.split_last().expect("nested in a module");
                let owner = format!("declarations nested in {}", self.schema.qualified(parent));
                claim(outer, name.clone(), owner);
            }
        }
        let mut generated = vec!["CLIENT_FINGERPRINT".to_string()];
        if self.role != Some(Role::Client) {
            generated.push("INTERNAL_FINGERPRINT".to_string());
        }
        generated.extend(self.received().map(dispatch_name));
        generated.extend(self.relayed().map(relay_name));
        for name in generated {
            let owner = format!("the generated `{name}`");
            claim(&[], name, owner);
        }
        // A variant qualified by its namespace can still meet another
        // message's: `aB.c.M` and `a.bC.M` are both `ABCM`.
        for space in self.received() {
            let name = dispatch_name(space);
            let messages = &space.messages;
            let mut seen = BTreeMap::new();
            for (variant, id) in self.variants(messages).into_iter().zip(messages) {
                if let Some(previous) = seen.insert(variant.clone(), *id) {
                    errors.push(format!(
                        "`{}` and `{}` both generate `{name}::{variant}`",
                        self.schema.qualified(previous),
                        self.schema.qualified(*id)
                    ));
                }
            }
        }
        if !errors.is_empty() {
            return Err(Error::new(errors.join("\n")));
        }
        Ok(())
    }

    /// The role pairs this role receives, each with a dispatch enum.
    fn received(&self) -> impl Iterator<Item = &'a Space> + use<'a, '_> {
        self.wire
            .spaces()
            .iter()
            .filter(|space| self.role.is_none_or(|role| role == space.to))
    }

    /// The role pairs this role sends or receives, each message of which
    /// implements `Link`.
    fn linked(&self) -> impl Iterator<Item = &'a Space> + use<'a, '_> {
        self.wire.spaces().iter().filter(|space| {
            self.role
                .is_none_or(|role| role == space.from || role == space.to)
        })
    }

    /// The role pairs an edge relays, between clients and sims or hubs,
    /// each with a relay table. Only edges have them.
    fn relayed(&self) -> impl Iterator<Item = &'a Space> + use<'a, '_> {
        let edge = self.role.is_none_or(|role| role == Role::Edge);
        self.wire.spaces().iter().filter(move |space| {
            edge && matches!(
                (space.from, space.to),
                (Role::Client, Role::Sim | Role::Hub) | (Role::Sim | Role::Hub, Role::Client)
            )
        })
    }

    /// Whether this role encodes or decodes declaration `id`, so it is
    /// generated at all.
    fn generated(&self, id: TypeId) -> bool {
        self.encode[id.0] || self.decode[id.0]
    }

    fn files(&self) -> Vec<GeneratedFile> {
        let mut root = Module::default();
        let mut defs: Vec<TypeId> = (0..self.schema.defs.len()).map(TypeId).collect();
        defs.sort_by_cached_key(|id| self.schema.qualified(*id));
        for namespace in &self.schema.namespaces {
            let mut module = &mut root;
            for segment in &namespace.name {
                module = module.children.entry(ident(segment)).or_default();
                module.file = true;
            }
        }
        for id in defs.into_iter().filter(|id| self.generated(*id)) {
            let mut module = &mut root;
            for segment in &self.modules[id.0] {
                module = module.children.entry(segment.clone()).or_default();
            }
            module.defs.push(id);
        }
        let mut consts: Vec<ConstId> = (0..self.schema.consts.len()).map(ConstId).collect();
        consts.sort_by_cached_key(|id| self.schema.const_qualified(*id));
        for id in consts {
            let mut module = &mut root;
            for segment in &self.const_modules[id.0] {
                module = module.children.entry(segment.clone()).or_default();
            }
            module.consts.push(id);
        }
        let mut files = Vec::new();
        self.file(&root, &mut Vec::new(), &mut files);
        files
    }

    /// Emits `module`, the root or a namespace, as its own file, and each
    /// namespace below it as theirs.
    fn file(&self, module: &Module, path: &mut Vec<String>, files: &mut Vec<GeneratedFile>) {
        let root = path.is_empty();
        let mut out = Out::default();
        out.line(HEADER);
        let namespaces: Vec<&String> = module
            .children
            .iter()
            .filter(|(_, child)| child.file)
            .map(|(name, _)| name)
            .collect();
        if !namespaces.is_empty() {
            out.line("");
            for name in namespaces {
                out.line(ALLOW);
                out.line(format!("pub mod {name};"));
            }
        }
        let kinds = self.wire.hubs().iter().any(|id| self.generated(*id));
        let linked = self.linked().next().is_some() || self.relayed().next().is_some();
        if root && (kinds || linked) {
            out.line("");
            out.line(format!("use {RUNTIME} as __w;"));
        }
        if root {
            let fingerprints = self.wire.fingerprints();
            out.line("");
            out.line("/// A hash of what clients see. A client and a server with different");
            out.line("/// client fingerprints cannot talk.");
            out.line(format!(
                "pub const CLIENT_FINGERPRINT: u64 = 0x{:016x};",
                fingerprints.client
            ));
            if self.role != Some(Role::Client) {
                out.line("");
                out.line("/// A hash of the whole schema. Servers with different internal");
                out.line("/// fingerprints cannot talk.");
                out.line(format!(
                    "pub const INTERNAL_FINGERPRINT: u64 = 0x{:016x};",
                    fingerprints.internal
                ));
            }
        }
        self.module(&mut out, module, path);
        if root {
            self.links(&mut out);
            self.hub_kinds(&mut out);
            self.relays(&mut out);
            for space in self.received() {
                self.dispatch(&mut out, space);
            }
        }
        // A raw identifier names its file without the `r#`.
        let mut file: PathBuf = path.iter().map(|s| s.trim_start_matches("r#")).collect();
        file.push(FILE);
        files.push(GeneratedFile::new(file, out.finish()));

        for (name, child) in &module.children {
            if child.file {
                path.push(name.clone());
                self.file(child, path, files);
                path.pop();
            }
        }
    }

    /// Writes `module`'s declarations, and the modules of their nested
    /// types inline; namespaces get files of their own.
    fn module(&self, out: &mut Out, module: &Module, path: &mut Vec<String>) {
        if !module.defs.is_empty() {
            out.line("");
            out.line(format!("use {RUNTIME} as __w;"));
        }
        if !module.consts.is_empty() {
            out.line("");
        }
        for id in &module.consts {
            self.constant(out, *id);
        }
        for id in &module.defs {
            out.line("");
            match &self.schema.def(*id).kind {
                DefKind::Enum(item) => self.enumeration(out, *id, item),
                DefKind::Struct(item) => self.object(out, *id, &item.fields, path),
                DefKind::Message(item) => {
                    self.object(out, *id, &item.fields, path);
                    self.message(out, *id, item);
                }
                DefKind::Hub(item) => self.object(out, *id, &item.fields, path),
                DefKind::Type(item) => self.newtype(out, *id, item, path),
                DefKind::Union(item) => self.union(out, *id, item, path),
            }
        }
        for (name, child) in &module.children {
            if child.file {
                continue;
            }
            out.line("");
            out.line(ALLOW);
            out.line(format!("pub mod {name} {{"));
            path.push(name.clone());
            self.module(out, child, path);
            path.pop();
            out.line("}");
        }
    }
}

/// A struct or message being emitted, or the fields of a union variant.
struct Object<'a> {
    /// The name errors report, as `Outer.Inner`, or `Union.Variant`.
    name: String,
    layout: &'a Layout,
    fields: &'a [Field],
    module: &'a [String],
    /// Whether the encoder finds field `i` bound as `__fi`, a reference, as
    /// a union's `match` binds a variant's fields; otherwise it reads
    /// `self.x`.
    bound: bool,
}

impl Object<'_> {
    fn field(&self, field: &Field) -> String {
        format!("{}.{}", self.name, field.name)
    }

    /// Field `i` as a `&T`.
    fn reference(&self, i: usize) -> String {
        if self.bound {
            format!("__f{i}")
        } else {
            format!("&self.{}", ident(&self.fields[i].name))
        }
    }

    /// Field `i` as the receiver of a method taking `&self`.
    fn receiver(&self, i: usize) -> String {
        if self.bound {
            format!("__f{i}")
        } else {
            format!("self.{}", ident(&self.fields[i].name))
        }
    }

    /// Field `i` followed by `suffix`, as a place: `self.x.0`, or the
    /// `Copy` value itself when `suffix` is empty.
    fn value(&self, i: usize, suffix: &str) -> String {
        match (self.bound, suffix) {
            (true, "") => format!("*__f{i}"),
            (true, _) => format!("__f{i}{suffix}"),
            (false, _) => format!("self.{}{suffix}", ident(&self.fields[i].name)),
        }
    }

    fn optional_count(&self) -> usize {
        self.layout
            .fields
            .iter()
            .filter(|slot| matches!(slot, Slot::Optional { .. }))
            .count()
    }
}

#[derive(Default)]
struct Module {
    defs: Vec<TypeId>,
    consts: Vec<ConstId>,
    children: BTreeMap<String, Module>,
    /// A namespace, or one enclosing a namespace, emitted as its own file;
    /// the modules of nested types are inline.
    file: bool,
}

/// Rejects types the Rust runtime has no values for yet.
fn unsupported(schema: &Schema) -> Result<(), Error> {
    fn find(ty: &Type) -> Option<&'static str> {
        match &ty.kind {
            TypeKind::UEntity => Some("uentity"),
            TypeKind::Uuid => Some("uuid"),
            TypeKind::Array(item, _) | TypeKind::Vec(item) | TypeKind::Set(item) => find(item),
            TypeKind::Map(key, value) => find(key).or_else(|| find(value)),
            _ => None,
        }
    }
    let mut errors = Vec::new();
    for (index, def) in schema.defs.iter().enumerate() {
        let fields = match &def.kind {
            DefKind::Enum(_) => continue,
            DefKind::Struct(item) => &item.fields,
            DefKind::Message(item) => &item.fields,
            DefKind::Hub(item) => {
                if let Some(name) = find(&item.key) {
                    errors.push(format!(
                        "`{}`: the Rust backend does not support `{name}` yet",
                        schema.qualified(TypeId(index))
                    ));
                }
                &item.fields
            }
            // Reported once here rather than at every field it types.
            DefKind::Type(item) => {
                if let Some(name) = find(&item.target) {
                    errors.push(format!(
                        "`{}`: the Rust backend does not support `{name}` yet",
                        schema.qualified(TypeId(index))
                    ));
                }
                continue;
            }
            DefKind::Union(item) => {
                for variant in &item.variants {
                    let tys: Vec<(String, &Type)> = match &variant.data {
                        VariantData::Unit => Vec::new(),
                        VariantData::Type(ty) => vec![(variant.name.clone(), ty)],
                        VariantData::Fields(fields) => fields
                            .iter()
                            .map(|field| (format!("{}.{}", variant.name, field.name), &field.ty))
                            .collect(),
                    };
                    for (label, ty) in tys {
                        if let Some(name) = find(ty) {
                            errors.push(format!(
                                "`{}.{label}`: the Rust backend does not support `{name}` yet",
                                schema.qualified(TypeId(index))
                            ));
                        }
                    }
                }
                continue;
            }
        };
        for field in fields {
            if let Some(name) = find(&field.ty) {
                errors.push(format!(
                    "`{}.{}`: the Rust backend does not support `{name}` yet",
                    schema.qualified(TypeId(index)),
                    field.name
                ));
            }
        }
    }
    if !errors.is_empty() {
        return Err(Error::new(errors.join("\n")));
    }
    Ok(())
}

/// Whether any variant of `item` has fields, and so a view in the union's
/// module.
fn has_fields(item: &crate::ir::Union) -> bool {
    item.variants
        .iter()
        .any(|variant| matches!(variant.data, VariantData::Fields(_)))
}

/// The pattern binding the fields of variant `name` as `__f0`, `__f1`, …,
/// in declaration order.
fn variant_pattern(name: &str, fields: &[Field]) -> String {
    let bindings: Vec<String> = fields
        .iter()
        .enumerate()
        .map(|(i, field)| format!("{}: __f{i}", ident(&field.name)))
        .collect();
    format!("Self::{name} {{ {} }}", bindings.join(", "))
}

/// The module `id` is declared in: its namespace's, then one per enclosing
/// declaration, so `a.Foo.Bar` lives in `a::foo`.
fn module(schema: &Schema, id: TypeId) -> Vec<String> {
    let def = schema.def(id);
    scope_module(schema, def.namespace, def.parent)
}

/// The module of what is declared in `parent`, or at the top of
/// `namespace`.
fn scope_module(schema: &Schema, namespace: NamespaceId, parent: Option<TypeId>) -> Vec<String> {
    match parent {
        Some(parent) => {
            let mut module = module(schema, parent);
            module.push(snake(&schema.def(parent).name));
            module
        }
        None => {
            let namespace = schema.namespace(namespace);
            namespace.name.iter().map(|name| ident(name)).collect()
        }
    }
}

/// Each const's name in `SCREAMING_SNAKE_CASE`: `MaxHp` is `MAX_HP`. A
/// name made only of underscores has no words to convert and is rejected.
fn const_names(schema: &Schema) -> Result<Vec<String>, Error> {
    let mut names = Vec::with_capacity(schema.consts.len());
    let mut errors = Vec::new();
    for (index, item) in schema.consts.iter().enumerate() {
        let name = case::shouty(&item.name);
        if name.is_empty() {
            errors.push(format!(
                "`{}` has no words to name a Rust constant",
                schema.const_qualified(ConstId(index))
            ));
        }
        // `_1` is `1`, which must not start an identifier.
        if name.starts_with(|ch: char| ch.is_ascii_digit()) {
            names.push(format!("_{name}"));
        } else {
            names.push(name);
        }
    }
    if !errors.is_empty() {
        return Err(Error::new(errors.join("\n")));
    }
    Ok(names)
}

/// `value` as a Rust string literal. Escaped by hand rather than with
/// `{:?}`, whose choices may change between Rust versions and churn
/// committed code.
fn string_literal(value: &str) -> String {
    let mut out = String::from("\"");
    for ch in value.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '\0' => out.push_str("\\0"),
            ch if ch.is_control() => out.push_str(&format!("\\u{{{:x}}}", ch as u32)),
            ch => out.push(ch),
        }
    }
    out.push('"');
    out
}

/// Whether `role` encodes each declaration, and whether it decodes it:
/// what the messages it sends and receives reach. Declarations no message
/// reaches get both. Hub kinds are generated, with both, only for hubs,
/// which store them, and sims, which cache them.
fn roles(schema: &Schema, role: Option<Role>) -> (Vec<bool>, Vec<bool>) {
    let len = schema.defs.len();
    let Some(role) = role else {
        return (vec![true; len], vec![true; len]);
    };
    struct Marker<'a> {
        schema: &'a Schema,
        encode: Vec<bool>,
        decode: Vec<bool>,
    }

    impl Marker<'_> {
        fn mark(&mut self, id: TypeId, roles: (bool, bool)) {
            let (enc, dec) = roles;
            if (!enc || self.encode[id.0]) && (!dec || self.decode[id.0]) {
                return;
            }
            let schema = self.schema;
            let mut named = Vec::new();
            match &schema.def(id).kind {
                DefKind::Struct(item) => fields_named(&item.fields, &mut named),
                DefKind::Message(item) => fields_named(&item.fields, &mut named),
                // Whoever reads or writes a kind's objects names them by key.
                DefKind::Hub(item) => {
                    named_in(&item.key, &mut named);
                    fields_named(&item.fields, &mut named);
                }
                DefKind::Type(item) => named_in(&item.target, &mut named),
                DefKind::Union(item) => {
                    for variant in &item.variants {
                        match &variant.data {
                            VariantData::Unit => {}
                            VariantData::Type(ty) => named_in(ty, &mut named),
                            VariantData::Fields(fields) => fields_named(fields, &mut named),
                        }
                    }
                }
                DefKind::Enum(_) => {}
            }
            self.encode[id.0] |= enc;
            self.decode[id.0] |= dec;
            for inner in named {
                self.mark(inner, roles);
            }
        }
    }

    fn fields_named(fields: &[Field], out: &mut Vec<TypeId>) {
        for field in fields {
            named_in(&field.ty, out);
        }
    }

    let mut marker = Marker {
        schema,
        encode: vec![false; len],
        decode: vec![false; len],
    };
    // No message reaches a kind's body, so only its holders get it.
    if matches!(role, Role::Hub | Role::Sim) {
        for (index, def) in schema.defs.iter().enumerate() {
            if matches!(def.kind, DefKind::Hub(_)) {
                marker.mark(TypeId(index), (true, true));
            }
        }
    }
    for (index, def) in schema.defs.iter().enumerate() {
        let DefKind::Message(item) = &def.kind else {
            continue;
        };
        let sends = item.links.iter().any(|link| link.from == role);
        let receives = item.links.iter().any(|link| link.to == role);
        if sends || receives {
            marker.mark(TypeId(index), (sends, receives));
        }
        // A sender names the object a message goes to by its kind's key.
        for link in item.links.iter().filter(|link| link.from == role) {
            if let Some(kind) = link.to_kind
                && let DefKind::Hub(hub) = &schema.def(kind).kind
            {
                let mut named = Vec::new();
                named_in(&hub.key, &mut named);
                for id in named {
                    marker.mark(id, (true, false));
                }
            }
        }
    }
    for (index, def) in schema.defs.iter().enumerate() {
        let reached = marker.encode[index] || marker.decode[index];
        if !reached && !matches!(def.kind, DefKind::Message(_) | DefKind::Hub(_)) {
            marker.mark(TypeId(index), (true, true));
        }
    }
    (marker.encode, marker.decode)
}

/// The dispatch enum of the messages linking a role pair:
/// `ClientToSimMessage`.
fn dispatch_name(space: &Space) -> String {
    format!("{}To{}Message", space.from.pascal(), space.to.pascal())
}

/// The relay table of a role pair: `CLIENT_TO_SIM_RELAYS`.
fn relay_name(space: &Space) -> String {
    format!(
        "{}_TO_{}_RELAYS",
        space.from.name().to_uppercase(),
        space.to.name().to_uppercase()
    )
}

/// The declarations `ty` names directly; a `type`'s target is reached
/// through its own declaration.
fn named_in(ty: &Type, out: &mut Vec<TypeId>) {
    match &ty.kind {
        TypeKind::Array(item, _) | TypeKind::Vec(item) | TypeKind::Set(item) => named_in(item, out),
        TypeKind::Map(key, value) => {
            named_in(key, out);
            named_in(value, out);
        }
        TypeKind::Named(id) => out.push(*id),
        _ => {}
    }
}

/// The traits each owned type derives: what all of its fields support,
/// assuming recursive types support everything until shown otherwise.
fn traits(schema: &Schema) -> Vec<Traits> {
    let mut traits = vec![ALL; schema.defs.len()];
    loop {
        let mut changed = false;
        for (index, def) in schema.defs.iter().enumerate() {
            let all = match &def.kind {
                DefKind::Enum(_) => continue,
                DefKind::Struct(item) => fields_traits(&item.fields, &traits),
                DefKind::Message(item) => fields_traits(&item.fields, &traits),
                DefKind::Hub(item) => fields_traits(&item.fields, &traits),
                DefKind::Type(item) => type_traits(&item.target, &traits),
                // A union has no variant to default to.
                DefKind::Union(item) => {
                    let mut all = Traits {
                        default: false,
                        ..ALL
                    };
                    for variant in &item.variants {
                        let variant_traits = match &variant.data {
                            VariantData::Unit => ALL,
                            VariantData::Type(ty) => type_traits(ty, &traits),
                            VariantData::Fields(fields) => fields_traits(fields, &traits),
                        };
                        all = all.and(variant_traits);
                    }
                    all
                }
            };
            if all != traits[index] {
                traits[index] = all;
                changed = true;
            }
        }
        if !changed {
            return traits;
        }
    }
}

/// What an object of `fields` supports. An optional field defaults to
/// `None`, whatever its type.
fn fields_traits(fields: &[Field], traits: &[Traits]) -> Traits {
    let mut all = ALL;
    for field in fields {
        let field_traits = type_traits(&field.ty, traits);
        all = all.and(Traits {
            default: field.optional || field_traits.default,
            ..field_traits
        });
    }
    all
}

fn type_traits(ty: &Type, traits: &[Traits]) -> Traits {
    match &ty.kind {
        TypeKind::F32 | TypeKind::F64 => Traits {
            eq: false,
            hash: false,
            ..ALL
        },
        // The runtime's identities and `SystemTime` have no default.
        TypeKind::Entity | TypeKind::Timestamp => Traits {
            default: false,
            ..ALL
        },
        TypeKind::String => Traits { copy: false, ..ALL },
        TypeKind::Bytes => match ty.constraints.fixed_length() {
            Some(len) => Traits {
                default: len <= 32,
                ..ALL
            },
            None => Traits { copy: false, ..ALL },
        },
        // `Default` covers arrays of up to 32 items.
        TypeKind::Array(item, len) => Traits {
            default: type_traits(item, traits).default && *len <= 32,
            ..type_traits(item, traits)
        },
        TypeKind::Vec(item) => Traits {
            default: true,
            copy: false,
            ..type_traits(item, traits)
        },
        TypeKind::Set(item) => Traits {
            eq: type_traits(item, traits).eq,
            hash: false,
            default: true,
            copy: false,
        },
        TypeKind::Map(key, value) => Traits {
            eq: type_traits(key, traits).eq && type_traits(value, traits).eq,
            hash: false,
            default: true,
            copy: false,
        },
        TypeKind::Named(id) => traits[id.0],
        _ => ALL,
    }
}

