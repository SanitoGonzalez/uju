use std::collections::BTreeSet;
use std::ffi::OsStr;
use std::fs;
use std::io::{self, BufRead, BufReader};
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use anyhow::{Context, Result, bail};
use clap::builder::PossibleValuesParser;
use clap::{Args, Parser, Subcommand, ValueEnum};
use uju_protoc::backend::{self, Backend, DISPATCHERS, GeneratedFile, MARKER, Options, PROTOCOLS};
use uju_protoc::compile;
use uju_protoc::ir::Direction;

/// The extension directories are searched for.
const EXTENSION: &str = "uju";

#[derive(Parser, Debug)]
#[command(name = "ujuc", version, about = "Compile uju schemas")]
struct Cli {
    #[command(subcommand)]
    command: Command,
}

#[derive(Subcommand, Debug)]
enum Command {
    /// Generate the protocol: every type, with its encoder and decoder, and
    /// the message ids
    Protocol {
        /// Target to generate; `ir` emits the compiled IR as JSON
        #[arg(
            value_name = "BACKEND",
            value_parser = PossibleValuesParser::new(PROTOCOLS.iter().copied()),
        )]
        backend: String,

        /// Generate only the peer receiving these messages: `in` for a
        /// server, `out` for a client. It decodes what it receives and
        /// encodes what it sends. Both peers are generated by default
        #[arg(long, value_enum, value_name = "DIRECTION")]
        direction: Option<Peer>,

        #[command(flatten)]
        common: Common,
    },
    /// Generate handler branches for the messages one peer receives
    Dispatch {
        /// Target to generate
        #[arg(
            value_name = "BACKEND",
            value_parser = PossibleValuesParser::new(DISPATCHERS.iter().copied()),
        )]
        backend: String,

        /// The peer receiving these messages: `in` for a server, `out` for a
        /// client
        #[arg(long, value_enum, value_name = "DIRECTION")]
        direction: Peer,

        #[command(flatten)]
        common: Common,
    },
}

#[derive(Args, Debug)]
struct Common {
    /// Directory to write generated files into
    #[arg(short = 'o', long = "out", value_name = "DIR", default_value = ".")]
    out: PathBuf,

    /// Compile and report what would be written, without writing it
    #[arg(long)]
    dry_run: bool,

    /// Schema files, or directories searched recursively for `*.uju`
    #[arg(value_name = "PATH", required = true)]
    paths: Vec<PathBuf>,
}

#[derive(Debug, Clone, Copy, ValueEnum)]
enum Peer {
    In,
    Out,
}

impl From<Peer> for Direction {
    fn from(peer: Peer) -> Direction {
        match peer {
            Peer::In => Direction::In,
            Peer::Out => Direction::Out,
        }
    }
}

fn main() -> ExitCode {
    match run(&Cli::parse().command) {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("ujuc: {error:#}");
            ExitCode::FAILURE
        }
    }
}

fn run(command: &Command) -> Result<()> {
    match command {
        Command::Protocol {
            backend,
            direction,
            common,
        } => {
            let options = Options {
                direction: direction.map(Direction::from),
            };
            let generator = backend::protocol(backend, &options).with_context(|| {
                format!(
                    "no protocol backend named `{backend}`; known: {}",
                    PROTOCOLS.join(", ")
                )
            })?;
            generate(&format!("protocol {backend}"), generator.as_ref(), common)
        }
        Command::Dispatch {
            backend,
            direction,
            common,
        } => {
            let generator = backend::dispatch(backend, (*direction).into()).with_context(|| {
                format!(
                    "no dispatch backend named `{backend}`; known: {}",
                    DISPATCHERS.join(", ")
                )
            })?;
            generate(&format!("dispatch {backend}"), generator.as_ref(), common)
        }
    }
}

/// Compiles the schemas in `args` and writes what `generator` emits from
/// them; `name` labels the output.
fn generate(name: &str, generator: &dyn Backend, args: &Common) -> Result<()> {
    let inputs = collect(&args.paths)?;
    if inputs.is_empty() {
        bail!("no `*.{EXTENSION}` files found");
    }
    let sources = inputs
        .iter()
        .map(|path| {
            fs::read_to_string(path).with_context(|| format!("reading `{}`", path.display()))
        })
        .collect::<Result<Vec<String>>>()?;

    let borrowed: Vec<&str> = sources.iter().map(String::as_str).collect();
    let schema = match compile(&borrowed) {
        Ok(schema) => schema,
        Err(mut diagnostics) => {
            diagnostics.sort_by_key(|diagnostic| (diagnostic.source.0, diagnostic.span.start));
            for diagnostic in &diagnostics {
                let index = diagnostic.source.0;
                let name = inputs[index].display().to_string();
                eprintln!("{}", diagnostic.render(&name, &sources[index]));
            }
            bail!("{} error(s); nothing was generated", diagnostics.len());
        }
    };

    let files = generator
        .generate(&schema)
        .with_context(|| format!("generating `{name}`"))?;
    if args.dry_run {
        for file in &files {
            println!("{}", args.out.join(&file.path).display());
        }
        println!(
            "{name}: {} file(s) -> {} (dry run, nothing written)",
            files.len(),
            args.out.display()
        );
    } else {
        write(&args.out, &files).with_context(|| format!("generating `{name}`"))?;
        println!("{name}: {} file(s) -> {}", files.len(), args.out.display());
    }

    // Advisory: a failed scan doesn't undo what was written.
    match stale(&args.out, &files) {
        Ok(paths) => {
            for path in paths {
                eprintln!(
                    "ujuc: warning: `{}` is stale: an earlier run generated it, this one \
                     didn't; delete it",
                    path.display()
                );
            }
        }
        Err(error) => eprintln!("ujuc: warning: checking for stale files: {error:#}"),
    }
    Ok(())
}

/// Expand the paths given on the command line: files are taken as they are,
/// directories are searched recursively for `*.uju`. A path reached twice —
/// listed twice, or listed alongside a directory containing it — is compiled
/// once, and each directory is listed in sorted order, so the same inputs
/// always lower to the same IR.
fn collect(paths: &[PathBuf]) -> Result<Vec<PathBuf>> {
    let mut files = Vec::new();
    let mut seen = BTreeSet::new();
    for path in paths {
        let metadata =
            fs::metadata(path).with_context(|| format!("reading `{}`", path.display()))?;
        if metadata.is_dir() {
            walk(path, &mut files, &mut seen)?;
        } else {
            push(path.clone(), &mut files, &mut seen)?;
        }
    }
    Ok(files)
}

fn walk(dir: &Path, files: &mut Vec<PathBuf>, seen: &mut BTreeSet<PathBuf>) -> Result<()> {
    // Directories are marked too, so a symlink cycle terminates.
    if !mark(dir, seen)? {
        return Ok(());
    }
    let mut entries: Vec<PathBuf> = fs::read_dir(dir)
        .and_then(|entries| {
            entries
                .map(|entry| entry.map(|entry| entry.path()))
                .collect()
        })
        .with_context(|| format!("reading `{}`", dir.display()))?;
    entries.sort();

    for entry in entries {
        if entry.is_dir() {
            walk(&entry, files, seen)?;
        } else if entry.extension() == Some(OsStr::new(EXTENSION)) {
            push(entry, files, seen)?;
        }
    }
    Ok(())
}

fn push(path: PathBuf, files: &mut Vec<PathBuf>, seen: &mut BTreeSet<PathBuf>) -> Result<()> {
    if mark(&path, seen)? {
        files.push(path);
    }
    Ok(())
}

/// Records `path` as visited, returning whether it had not been seen before.
fn mark(path: &Path, seen: &mut BTreeSet<PathBuf>) -> Result<bool> {
    let canonical =
        fs::canonicalize(path).with_context(|| format!("resolving `{}`", path.display()))?;
    Ok(seen.insert(canonical))
}

/// Files under `dir` an earlier run generated and this one didn't: those
/// sharing an extension with `files` whose first line holds [`MARKER`]. No
/// generated module declares them any more, so they only linger.
/// Hand-written files lack the marker; hidden directories and symlinks are
/// skipped.
fn stale(dir: &Path, files: &[GeneratedFile]) -> Result<Vec<PathBuf>> {
    let generated: BTreeSet<PathBuf> = files.iter().map(|file| dir.join(&file.path)).collect();
    let extensions: BTreeSet<&OsStr> = files
        .iter()
        .filter_map(|file| file.path.extension())
        .collect();
    let mut found = Vec::new();
    if dir.is_dir() {
        scan(dir, &generated, &extensions, &mut found)?;
    }
    Ok(found)
}

fn scan(
    dir: &Path,
    generated: &BTreeSet<PathBuf>,
    extensions: &BTreeSet<&OsStr>,
    found: &mut Vec<PathBuf>,
) -> Result<()> {
    let mut entries: Vec<fs::DirEntry> = fs::read_dir(dir)
        .and_then(|entries| entries.collect())
        .with_context(|| format!("reading `{}`", dir.display()))?;
    entries.sort_by_key(|entry| entry.path());
    for entry in entries {
        let path = entry.path();
        // Doesn't follow symlinks.
        let kind = entry
            .file_type()
            .with_context(|| format!("reading `{}`", path.display()))?;
        if kind.is_dir() {
            if !entry.file_name().to_string_lossy().starts_with('.') {
                scan(&path, generated, extensions, found)?;
            }
        } else if kind.is_file()
            && path.extension().is_some_and(|ext| extensions.contains(ext))
            && !generated.contains(&path)
            && marked(&path)?
        {
            found.push(path);
        }
    }
    Ok(())
}

/// Whether the first line of the file at `path` holds [`MARKER`].
fn marked(path: &Path) -> Result<bool> {
    let file = fs::File::open(path).with_context(|| format!("reading `{}`", path.display()))?;
    let mut line = String::new();
    match BufReader::new(file).read_line(&mut line) {
        Ok(_) => Ok(line.contains(MARKER)),
        // Not text, so not generated.
        Err(error) if error.kind() == io::ErrorKind::InvalidData => Ok(false),
        Err(error) => Err(error).with_context(|| format!("reading `{}`", path.display())),
    }
}

fn write(dir: &Path, files: &[GeneratedFile]) -> Result<()> {
    fs::create_dir_all(dir).with_context(|| format!("creating `{}`", dir.display()))?;
    for file in files {
        let path = dir.join(&file.path);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)
                .with_context(|| format!("creating `{}`", parent.display()))?;
        }
        fs::write(&path, &file.contents)
            .with_context(|| format!("writing `{}`", path.display()))?;
    }
    Ok(())
}
